"""Generate representation adapters for original time-series functions."""

import argparse
import json
from pathlib import Path

from generate_graph_bindings import (
    argument_names,
    snake,
    source_prose,
    split_top,
    type_spec,
)

ROOT = Path(__file__).resolve().parent.parent
TYPES = {
    "Series": ("HMath.TimeSeries.Core", 120),
    "Alignment": ("HMath.TimeSeries.Core", 121),
    "Fill": ("HMath.TimeSeries.Core", 122),
    "Resampling": ("HMath.TimeSeries.Core", 123),
    "Rolling": ("HMath.TimeSeries.Core", 124),
    "DTWResult": ("HMath.TimeSeries.Diagnostics", 125),
    "Deterministic": ("HMath.TimeSeries.Diagnostics", 126),
    "ForecastMetric": ("HMath.TimeSeries.Diagnostics", 127),
    "Stationarity": ("HMath.TimeSeries.Diagnostics", 128),
    "ARIMAModel": ("HMath.TimeSeries.Models", 129),
    "ARModel": ("HMath.TimeSeries.Models", 130),
    "Decomposition": ("HMath.TimeSeries.Models", 131),
    "SARIMAOrder": ("HMath.TimeSeries.Models", 132),
    "STLConfig": ("HMath.TimeSeries.Models", 133),
    "Smoothing": ("HMath.TimeSeries.Models", 134),
    "VARModel": ("HMath.TimeSeries.Models", 135),
    "GaussianState": ("HMath.Signal", 140),
}


def generate():
    entries = json.loads(
        (ROOT / "bindings/schema/timeseries-functions.json").read_text()
    )["functions"]
    known = {*TYPES, "OptimizeOptions"}
    numeric = {
        e["module"] + "." + e["name"]
        for e in json.loads((ROOT / "bindings/schema/numeric.json").read_text())[
            "functions"
        ]
    }
    header = [
        '/* SPDX-License-Identifier: MPL-2.0 */\n/* Generated by tools/generate_timeseries_bindings.py. */\n#ifndef HMATH_TIMESERIES_H\n#define HMATH_TIMESERIES_H\n#include "hmath_value.h"\n#ifdef __cplusplus\nextern "C" {\n#endif\n',
        "/* Borrowed immutable inputs; successful outputs own one Value reference.\n * Error outputs are untouched. Original binary64 arithmetic, time ordering,\n * missingness, model fitting, diagnostics, budgets and seeds are preserved.\n * OptimizeOptions accepts original kind20 objects from the optimization API.\n * Source MathError returns status11 and hmath_last_math_error payload.\n * Cancellation is checked before entry, source budgets govern evaluation. */\n",
    ]
    c = [
        '/* SPDX-License-Identifier: MPL-2.0 */\n/* Generated; do not edit. */\n#include "hmath_timeseries.h"\n#include "value_internal.h"\nextern int hm_timeseries_apply(int, void *const *, size_t, void **);\n'
    ]
    hs = [
        "{-# LANGUAGE ForeignFunctionInterface #-}\n{-# LANGUAGE FlexibleInstances #-}\n{-# OPTIONS_GHC -Wno-orphans #-}\n-- SPDX-License-Identifier: MPL-2.0\n-- Generated representation adapters; all mathematics remains in original modules.\nmodule HMath.FFI.TimeSeries where\nimport Foreign\nimport Foreign.C\nimport HMath.FFI.Boundary\nimport HMath.FFI.Value\nimport HMath.FFI.GraphCodec (Wire(..),boxed,unboxed)\nimport qualified HMath.TimeSeries as T\nimport qualified HMath.Signal as S\nimport qualified HMath.Optimization.Common as O\n",
        "instance Wire O.OptimizeOptions where\n    wire = boxed 20\n    unwire = unboxed 20\n",
    ]
    py = [
        '# SPDX-License-Identifier: MPL-2.0\n# Generated by tools/generate_timeseries_bindings.py.\n"""Original timestamped-series, diagnostics and forecasting functions."""\nfrom ._timeseries_base import _invoke\nfrom ._value import Value, register\n',
    ]
    docs = [
        "# Time-series bindings\n\nC includes `hmath_timeseries.h`; Python uses `from hmath import timeseries`. These functions call the original Haskell time-series implementation. Timestamps retain caller-defined units, ordering and explicit missing values; no calendar interpretation or automatic data cleaning is added. The source observation, work and fitting limits remain in force.\n\n",
        "All inputs are borrowed during a synchronous call; every successful C output owns one [structured value](values.md) reference. Outputs are unchanged on error. Checked `Left MathError` returns status11 with the original structured error. Immutable objects support concurrent readers with independent references and output addresses. Python owners have `close()` and context managers. `Maybe Double` observations use `None` for missingness. Forecast models and configuration constructors retain the original argument order and defaults. `OptimizeOptions` comes from `hmath.optimization`.\n\n",
        "ARMA/SARIMA use the original local conditional sum-of-squares fit, not a substituted exact likelihood model. Stationarity and interval estimates are not inferred by forecasting calls. Refer to the linked source contract for each model and diagnostic.\n\n",
    ]
    mappings = []
    for name, (module, tag) in TYPES.items():
        qualifier = "S" if module == "HMath.Signal" else "T"
        hs.append(
            f"instance Wire {qualifier}.{name} where\n    wire = boxed {tag}\n    unwire = unboxed {tag}\n"
        )
        py.append(
            f'\n\nclass {name}(Value):\n    """Owned immutable original {module}.{name}."""\n\n\nregister({tag}, {name})\n'
        )
        header.append(
            f"typedef hmath_value hmath_timeseries_{snake(name)}_object; /* kind{tag} */\n"
        )
        # A type/constructor with the same source name is one inventory entry.
        if name not in {e["name"] for e in entries}:
            mappings.append(
                {
                    "symbol": module + "." + name,
                    "c": ["hmath_timeseries_" + snake(name) + "_object"],
                    "python": "hmath.timeseries." + name,
                    "specializations": ["original concrete type"],
                }
            )
    header.append(
        "/* Return the original Show representation as an owned String Value. */\nHMATH_API hmath_status hmath_timeseries_describe(hmath_context *context, const hmath_value *value, hmath_value **out);\n"
    )
    c.append(
        'extern int hm_timeseries_describe(void *,void **);\nhmath_status hmath_timeseries_describe(hmath_context *context,const hmath_value *value,hmath_value **out) {\n    if (!value || !out) return hm_error(HMATH_INVALID_ARGUMENT,"NULL time-series description argument");\n    hmath_value *temporary = NULL;\n    hmath_status status = hm_value_begin(context,&temporary);\n    if (status) return status;\n    int code = hm_timeseries_describe(hm_value_stable(value),&temporary->stable);\n    return hm_value_finish(temporary,code,out);\n}\n'
    )
    hs.append(
        'foreign export ccall "hm_timeseries_describe" describe :: StablePtr Value -> Ptr (StablePtr Value) -> IO CInt\ndescribe :: StablePtr Value -> Ptr (StablePtr Value) -> IO CInt\ndescribe input out = boundary $ do\n    value <- deRefStablePtr input\n    text <- case value of\n'
    )
    for name, (module, tag) in TYPES.items():
        qualifier = "S" if module == "HMath.Signal" else "T"
        hs.append(
            f"        Opaque {tag} _ _ _ _ -> show <$> (unwire value :: IO {qualifier}.{name})\n"
        )
    hs.append(
        '        _ -> invalid "expected a time-series domain object"\n    publish (Text text) out\n    pure 0\n'
    )
    py.append(
        '\n\ndef describe(value):\n    """Return the original Haskell Show representation of a domain object."""\n    return _invoke("hmath_timeseries_describe", [["SeriesObject"]], [value])\n'
    )
    docs.append(
        "## `describe`\n\n`timeseries.describe(value)` returns the original Haskell `Show` representation of one time-series object or Gaussian state. It preserves the original constructor and fields as text, including Unicode and embedded NUL. C receives an owned String value through `hmath_timeseries_describe(context, value, out)`. Mathematical operations use the typed object directly.\n\n"
    )
    hs += [
        'foreign export ccall "hm_timeseries_apply" apply :: CInt -> Ptr (StablePtr Value) -> CSize -> Ptr (StablePtr Value) -> IO CInt\n',
        "apply :: CInt -> Ptr (StablePtr Value) -> CSize -> Ptr (StablePtr Value) -> IO CInt\napply operation input arity out = boundary $ do\n    values <- peekArray (fromIntegral arity) input >>= mapM deRefStablePtr\n    case (operation,values) of\n",
    ]
    for operation, entry in enumerate(entries):
        signature = split_top(entry["signature"], "->")
        arguments, result = signature[:-1], signature[-1]
        checked = result.startswith("Either MathError ")
        result = result.removeprefix("Either MathError ")
        specifications = [type_spec(t, known) for t in arguments]
        type_spec(result, known)
        args = argument_names(entry, len(arguments))
        constructors = {
            "DTWResult": "distance path",
            "Stationarity": "statistic critical_values observations null_hypothesis",
            "Decomposition": "trend seasonal remainder",
            "SARIMAOrder": "ar difference ma seasonal_ar seasonal_difference seasonal_ma period",
            "STLConfig": "period seasonal_window trend_window low_pass_window inner_iterations robust_iterations",
            "Simple": "alpha",
            "Holt": "alpha beta",
            "HoltWinters": "period alpha beta gamma",
            "MASE": "period training",
        }
        if entry["name"] in constructors:
            args = constructors[entry["name"]].split()
            if len(args) != len(arguments):
                raise ValueError("time-series constructor fields differ")
        name = snake(entry["name"])
        symbol = "hmath_timeseries_" + name
        source = entry["module"] + "." + entry["name"]
        declaration = [
            "hmath_context *context",
            *["const hmath_value *" + arg for arg in args],
            "hmath_value **out",
        ]
        prototype = f"hmath_status {symbol}(" + ", ".join(declaration) + ")"
        header.append(
            f"/* {source} :: {entry['signature']} */\nHMATH_API {prototype};\n"
        )
        c.append(
            prototype
            + " {\n    if (!out"
            + "".join(" || !" + a for a in args)
            + ')\n        return hm_error(HMATH_INVALID_ARGUMENT,"NULL time-series argument");\n    hmath_value *temporary = NULL;\n    hmath_status status = hm_value_begin(context,&temporary);\n    if (status) return status;\n'
        )
        c.append(
            "    void *arguments[] = {"
            + (", ".join("hm_value_stable(" + a + ")" for a in args) or "NULL")
            + "};\n"
        )
        c.append(
            f"    int code = hm_timeseries_apply({operation},arguments,{len(args)},&temporary->stable);\n    return hm_value_finish(temporary,code,out);\n}}\n"
        )
        hs.append(
            f"        ({operation},["
            + ",".join("v" + arg for arg in args)
            + "]) -> do\n"
        )
        hs += [f"            {arg} <- unwire v{arg}\n" for arg in args]
        qualifier = "S" if entry["module"] == "HMath.Signal" else "T"
        call = qualifier + "." + entry["name"] + (" " + " ".join(args) if args else "")
        hs.append(
            "            checked ("
            + (call if checked else "Right (" + call + ")")
            + ") (\\result_value -> publish (wire result_value) out)\n"
        )
        py.append(
            f'\n\ndef {name}({", ".join(args)}):\n    """{source} :: {entry["signature"]}."""\n    return _invoke({symbol!r}, {specifications!r}, [{", ".join(args)}])\n'
        )
        docs.append(
            f"## `{name}`\n\n`timeseries.{name}({', '.join(args)})`\n\n{source_prose(entry)}\n\nOriginal: [`{source}`](haskell/{entry['module'].replace('.', '-')}.md#v:{entry['name']}).\n\n```haskell\n{entry['signature']}\n```\n\n```c\n{prototype};\n```\n\n"
        )
        if source not in numeric:
            mappings.append(
                {
                    "symbol": source,
                    "c": [symbol],
                    "python": "hmath.timeseries." + name,
                    "specializations": ["original concrete types"],
                }
            )
    hs.append(
        '        _ -> invalid "time-series operation identifier or arity differs"\n'
    )
    header.append("#ifdef __cplusplus\n}\n#endif\n#endif\n")
    return {
        "include/hmath_timeseries.h": "".join(header),
        "cbits/timeseries.c": "".join(c),
        "src/HMath/FFI/TimeSeries.hs": "".join(hs),
        "bindings/python/_hmath_native/timeseries.py": "".join(py),
        "docs/reference/timeseries-bindings.md": "".join(docs),
        "bindings/schema/timeseries-objects.json": json.dumps(
            {"schema": 1, "bindings": mappings}, indent=2
        )
        + "\n",
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for name, content in generate().items():
        path = ROOT / name
        if args.check:
            if not path.exists() or path.read_text() != content:
                parser.exit(1, "Stale time-series binding: " + name + "\n")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)


if __name__ == "__main__":
    main()
