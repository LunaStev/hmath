"""Generate the wheel catalog and audit original optimization dispatch coverage."""

import argparse
import ast
import json
import pprint
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    entries = json.loads((ROOT / "bindings/schema/optimization.json").read_text())[
        "functions"
    ]
    names = [entry["name"] for entry in entries]
    assert len(names) == len(set(names)), "duplicate source dispatch name"
    header = (ROOT / "include/hmath_optimization_all.h").read_text()
    native = (ROOT / "cbits/optimization_all.c").read_text()
    haskell = (ROOT / "src/HMath/FFI/OptimizationAll.hs").read_text()
    python = ast.parse(
        (ROOT / "bindings/python/_hmath_native/_optimization_all.py").read_text()
    )
    functions = {
        node.name: node for node in python.body if isinstance(node, ast.FunctionDef)
    }
    for entry in entries:
        name, symbol = entry["name"], entry["c"]
        assert len(entry["parameters"]) == len(entry["arguments"]), name
        assert re.search(r"\b" + symbol + r"\s*\(", header), symbol + " header"
        assert re.search(r"\b" + symbol + r"\s*\(", native), symbol + " C"
        assert 'return invoke(context, "' + name + '"' in native, name + " C dispatch"
        assert (
            '"' + name + '" -> apply ' + entry["expression"] + " arguments" in haskell
        ), name + " Haskell dispatch"
        if name[0].islower() and name not in {"initializeOptimizer", "optimizerStep"}:
            assert entry["python"] in functions, name + " Python function"
            parameters = [node.arg for node in functions[entry["python"]].args.args]
            assert parameters == entry["parameters"], name + " Python parameters"
    output = (
        "# SPDX-License-Identifier: MPL-2.0\n# Generated by tools/generate_optimization_bindings.py; do not edit.\nCATALOG = "
        + pprint.pformat(entries, width=88, sort_dicts=False)
        + "\n"
    )
    path = ROOT / "bindings/python/_hmath_native/_optimization_catalog.py"
    if args.check:
        existing = ast.literal_eval(ast.parse(path.read_text()).body[0].value)
        assert existing == entries, "generated optimization wheel catalog is stale"
    else:
        path.write_text(output)
    print(f"Optimization catalog: {len(entries)} original named dispatches verified.")


if __name__ == "__main__":
    main()
