import re


def snake(name):
    # Preserve acronym runs: solveMatrixLU -> solve_matrix_lu.
    return re.sub(
        r"([a-z0-9])([A-Z])", r"\1_\2", re.sub(r"([A-Z]+)([A-Z][a-z])", r"\1_\2", name)
    ).lower()


def symbol(mod, name, prec):
    return (
        "hmath_dense_"
        + ({"M": "", "L": "lu_", "Q": "qr_"}[mod])
        + snake(name)
        + "_f"
        + str(prec)
    )


def parameters(module, name, args):
    root = name.removesuffix("Checked")
    fixed = {
        "fromList": ["rows", "columns", "values"],
        "zeroMatrix": ["rows", "columns"],
        "diagonal": ["values"],
        "at": ["matrix", "row", "column"],
        "sliceMatrix": ["start_row", "start_column", "rows", "columns", "matrix"],
        "reshape": ["rows", "columns", "matrix"],
        "identity": ["order"],
        "scaleMatrix": ["scalar", "matrix"],
    }
    if module == "M" and root in fixed:
        return fixed[root]
    if name.endswith("WithTolerance"):
        return ["tolerance", "matrix"]
    if name.startswith("ridge"):
        return ["lambda_", "matrix", "rhs"]
    return [
        (
            "factors"
            if t in "lq"
            else "matrix"
            if i == 0
            else "rhs"
            if module in "LQ"
            else "right"
        )
        if t in "mlq"
        else "rhs"
        if t == "v"
        else "scalar"
        for i, t in enumerate(args)
    ]


