"""Add owned-Value specializations without duplicating original source coverage."""

import argparse
import json
from pathlib import Path

from generate_numeric_bindings import prefix

ROOT = Path(__file__).resolve().parent.parent


def generate():
    entries = [
        entry
        for entry in json.loads((ROOT / "bindings/schema/numeric.json").read_text())[
            "functions"
        ]
        if entry.get("specializations")
    ]
    assert len(entries) == 31
    entries += [
        entry
        for entry in json.loads((ROOT / "bindings/schema/numeric.json").read_text())[
            "functions"
        ]
        if entry["name"] in {"hammingDistance", "jaccardDistance"}
        and entry["module"] == "HMath.Geometry.Primitives"
    ]
    assert len(entries) == 33
    header = [
        '/* SPDX-License-Identifier: MPL-2.0 */\n/* Generated by tools/generate_numeric_objects.py. */\n#ifndef HMATH_NUMERIC_OBJECTS_H\n#define HMATH_NUMERIC_OBJECTS_H\n#include "hmath_value.h"\n#ifdef __cplusplus\nextern "C" {\n#endif\n',
        "/* Additional type instances of existing source functions; no new source\n * coverage is claimed. Actual Coefficient witnesses retain Float/Double, exact\n * Integer/Rational, bounded/native integers, Complex, nested Numeric.Dual and\n * Num-only Numeric.Quaternion. Original AD.Dual (including nested supported\n * leaves) and AD.Expr use distinct original Num/Fractional/Floating instances.\n * Eq/Ord/Integral/Bounded are required only where the original signature needs\n * them. AD.Expr has no Eq/Ord; Numeric.Dual/Quaternion have no Ord. Unsupported\n * instances return UNSUPPORTED; no ordering or arithmetic instance is invented.\n * clamp/min/max use actual native Ord dictionaries, including supported public\n * labels and recursively typed lists/tuples/Maybe. All inputs are borrowed;\n * outputs own one reference and remain untouched on failure. The prototype\n * selects the actual numeric type (required for empty lists), and all numeric\n * values must have that same actual type. Source exceptions/MathErrors remain\n * unchanged. Arbitrary user-defined Haskell instances need compiled adapters. */\n",
    ]
    c = [
        '/* SPDX-License-Identifier: MPL-2.0 */\n/* Generated by tools/generate_numeric_objects.py. */\n#include "hmath_numeric_objects.h"\n#include "value_internal.h"\nextern int hm_numeric_objects_apply(int,void *,void *const *,size_t,void **);\n'
    ]
    specializations = []
    docs = [
        "# Typed generic numeric APIs\n\nThese are additional type instances of the same Basic, Scalar, Linear, Statistics and Geometry equality functions, not additional source functions. Existing flat C APIs and Python dtype defaults remain unchanged. C includes `hmath_numeric_objects.h`; each original prefix gains `_value` and an explicit borrowed typed prototype, with owned Value outputs.\n\n",
        'Python automatically selects this path when an argument contains a native numeric owner (recursively through lists), including `Numeric.Dual`, `Numeric.Quaternion`, original `Autodiff.Dual` and symbolic `Autodiff.Expr`. Use `dtype=prototype` for empty vectors, or `dtype="value"` for ordinary values using their exact encoded type, such as unbounded integers or ordered strings/Booleans/tuples/lists. All numeric operands must have the same actual Haskell type; no implicit widening or conversion between the two distinct Dual types occurs.\n\n',
        "The actual Coefficient dictionaries preserve all existing standard primitive numeric instances, recursively nested Numeric.Dual and Quaternion where permitted. Original AD.Dual dictionaries preserve its primal-only ordering and full-field equality. Symbolic AD.Expr has Num/Fractional/Floating but no Eq/Ord: normalization and median therefore reject it. Numeric.Quaternion has Num only, so fractional/floating statistics reject it; Numeric.Dual has no Ord. Integral/Bounded operations keep their actual bounded instances and reject nonintegral objects. Ord-only clamp/min/max use the shared resolver for supported native public labels, lists, tuples and optional values, calling the actual original Ord dictionary. Geometry hamming/jaccard Value paths retain the shared native Eq dictionaries: exact coefficients, Numeric.Dual/Quaternion, supported original AD.Dual, structural values and supported domain owners. They do not substitute an ordering comparison for equality. Arbitrary user-defined Haskell instances require a compiled bridge; these finite adapters do not claim universal typeclass coverage.\n\n",
        '```python\nfrom hmath import scalar, statistics, numeric_types\n\nwith numeric_types.dual(2.0, 1.0) as x, numeric_types.dual(3.0, 0.0) as y:\n    with scalar.add(x, y) as z:\n        assert numeric_types.primal(z) == 5.0\n    with statistics.mean([x, y]) as mean:\n        assert numeric_types.primal(mean) == 2.5\n\nassert scalar.minimum_scalar("alpha", "beta", dtype="value") == "alpha"\n```\n\n',
    ]
    symbols = []
    for operation, entry in enumerate(entries):
        symbol = prefix(entry) + "_value"
        params = [
            a["name"] + "_" if a["name"] in ("class", "from", "lambda") else a["name"]
            for a in entry["args"]
        ]
        parameters = ", ".join(
            ["hmath_context *context", "const hmath_value *prototype"]
            + ["const hmath_value *" + name for name in params]
            + ["hmath_value **out"]
        )
        header.append(
            "/* "
            + entry["module"]
            + "."
            + entry["name"]
            + "; original typeclass constraints. */\nHMATH_API hmath_status "
            + symbol
            + "("
            + parameters
            + ");\n"
        )
        c.append(
            "hmath_status "
            + symbol
            + "("
            + parameters
            + ") {\n    if(!out||!prototype"
            + "".join("||!" + name for name in params)
            + ')return hm_error(HMATH_INVALID_ARGUMENT,"NULL typed numeric argument");\n    hmath_value *result=NULL;\n    hmath_status status=hm_value_begin(context,&result);\n    if(status)return status;\n    void *arguments[]={'
            + ",".join("hm_value_stable(" + name + ")" for name in params)
            + "};\n    return hm_value_finish(result,hm_numeric_objects_apply("
            + str(operation)
            + ",hm_value_stable(prototype),arguments,"
            + str(len(params))
            + ",&result->stable),out);\n}\n"
        )
        symbols.append(symbol)
        specializations.append(
            {
                "symbol": entry["module"] + "." + entry["name"],
                "additional_c": symbol,
                "python": "hmath."
                + entry["module"].removeprefix("HMath.").replace(".", "_").lower()
                + "."
                + entry["python"],
                "instances": "actual existing Coefficient/AD dictionaries allowed by original constraints; Ord/Eq-only functions additionally use supported native label dictionaries",
            }
        )
        docs.append(
            "## `"
            + specializations[-1]["python"]
            + "`\n\nAdditional Value specialization for the [same original function](haskell/"
            + entry["module"].replace(".", "-")
            + ".md#v:"
            + entry["name"]
            + ").\n\n```c\nhmath_status "
            + symbol
            + "("
            + parameters
            + ");\n```\n\n"
        )
    header.append("#ifdef __cplusplus\n}\n#endif\n#endif\n")
    return {
        "include/hmath_numeric_objects.h": "".join(header),
        "cbits/numeric_objects.c": "".join(c),
        "bindings/schema/numeric-object-specializations.json": json.dumps(
            {"schema": 1, "additional_specializations": specializations}, indent=2
        )
        + "\n",
        "bindings/schema/numeric-object-symbols.txt": "\n".join(symbols) + "\n",
        "docs/reference/numeric-objects.md": "".join(docs),
    }


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--check", action="store_true")
    args = p.parse_args()
    for name, content in generate().items():
        path = ROOT / name
        if args.check:
            if not path.exists() or path.read_text() != content:
                p.exit(1, "Stale typed numeric binding: " + name + "\n")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)


if __name__ == "__main__":
    main()
