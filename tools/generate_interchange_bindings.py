def normalize(text):
    text = re.sub(r"^forall\b.*?\.\s*", "", text)
    text = re.sub(r"^Element a\s*=>\s*", "", text)
    return (
        text.replace("HMath.Matrix.Matrix a", "Value")
        .replace("HMath.Tensor.Tensor a", "Value")
        .replace("FilePath", "String")
        .replace("MappedArray s", "MappedArray")
    )


def spec(text):
    text = text.strip()
    arrows = split_top(text, "->")
    if len(arrows) > 1:
        return ["function", *[spec(a) for a in arrows]]
    if text.startswith("IO "):
        return ["io", spec(text[3:])]
    if text.startswith("Either InterchangeError "):
        return ["either", spec(text.removeprefix("Either InterchangeError "))]
    if text.startswith("Maybe "):
        return ["maybe", spec(text[6:])]
    if text.startswith("[") and text.endswith("]"):
        return ["list", spec(text[1:-1])]
    if text.startswith("(") and text.endswith(")"):
        fields = split_top(text[1:-1], ",")
        if len(fields) > 1:
            return ["tuple", *[spec(field) for field in fields]]
        return ["unit"] if not fields[0] else spec(text[1:-1])
    if text not in {
        *TYPES,
        "Value",
        "Int",
        "Integer",
        "Bool",
        "String",
        "Char",
        "ByteString",
        "Word32",
        "Handle",
        "GetProgram",
    }:
        raise ValueError("unsupported interchange representation: " + text)
    return [text]


def wrapper(symbol, operation, names):
    declaration = ", ".join(
        [
            "hmath_context *context",
            *["const hmath_value *" + n for n in names],
            "hmath_value **out",
        ]
    )
    prototype = "hmath_status " + symbol + "(" + declaration + ")"
    c = (
        prototype
        + " {\n    const hmath_value *arguments[]={"
        + (",".join(names) or "NULL")
        + "};\n    return invoke(context,"
        + json.dumps(operation)
        + f",arguments,{len(names)},out);\n}}\n"
    )
    return prototype, c


def generate():
    entries = json.loads(
        (ROOT / "bindings/schema/interchange-functions.json").read_text()
    )["functions"]
    header = [
        '/* SPDX-License-Identifier: MPL-2.0 */\n/* Generated by tools/generate_interchange_bindings.py. */\n#ifndef HMATH_INTERCHANGE_H\n#define HMATH_INTERCHANGE_H\n#include "hmath_bytes.h"\n#include "hmath_callback.h"\n#include "hmath_interchange_error.h"\n#include "hmath_linear.h"\n#ifdef __cplusplus\nextern "C" {\n#endif\n',
        "/* Original fixed-width array formats, Element dictionaries, IO and scoped\n * mappings. All inputs are borrowed Value handles; each successful output owns\n * one reference. Failure leaves output pointers untouched. Source Left errors\n * return13 with hmath_last_interchange_error, not MathError. Callbacks use the\n * common kind101 tuple-argument protocol and may reenter checked APIs. Mapping\n * reads are valid only during withMappedArray; original retired-capability\n * checks reject reads after exit. Bytes copies can survive that scope.\n * File writes retain original partial-write/encoding-before-write semantics.\n * Typed Element operations take a scalar/Boolean prototype first, selecting\n * exactly one of the original13 fixed-width dictionaries. */\n",
    ]
    c = [
        '/* SPDX-License-Identifier: MPL-2.0 */\n/* Generated; do not edit. */\n#include "hmath_interchange.h"\n#include "value_internal.h"\n#include <stdlib.h>\nextern int hm_interchange_apply(const char *,void *const *,size_t,void **);\nstatic hmath_status invoke(hmath_context *context,const char *operation,const hmath_value *const *arguments,size_t count,hmath_value **out) {\n    if(!out || (count && !arguments))return hm_error(HMATH_INVALID_ARGUMENT,"NULL interchange arguments/output");\n    for(size_t i=0;i<count;++i)if(!arguments[i])return hm_error(HMATH_INVALID_ARGUMENT,"NULL interchange value");\n    if(count>(size_t)PTRDIFF_MAX/sizeof(void *))return hm_error(HMATH_OVERFLOW,"interchange argument span overflow");\n    void **stable=malloc((count?count:1)*sizeof *stable);\n    if(!stable)return hm_error(HMATH_ALLOCATION_FAILED,"interchange arguments allocation failed");\n    for(size_t i=0;i<count;++i)stable[i]=hm_value_stable(arguments[i]);\n    hmath_value *result=NULL;\n    hmath_status status=hm_value_begin(context,&result);\n    if(status){free(stable);return status;}\n    int code=hm_interchange_apply(operation,stable,count,&result->stable);\n    free(stable);\n    return hm_value_finish(result,code,out);\n}\n'
    ]
    py = [
        "# SPDX-License-Identifier: MPL-2.0\n# Generated by tools/generate_interchange_bindings.py.\nfrom ._interchange_base import (Array,InterchangeError,Limits,DType,Endian,Order,Compression,RawSpec,MappedArray,GetProgram,PutProgram,BinaryHandle,Bytes,_invoke,_element_type,_get_element,_put_element,_from_values,_to_values,_mapped_value)\n"
    ]
    hs = []
    docs = [
        "# Array interchange\n\nPython uses `from hmath import interchange`; C includes `hmath_interchange.h`. These adapters call the original Haskell array, binary/text/NumPy, compression, streaming and mapped-file functions. Source byte/shape/archive budgets, checksums, metadata, byte order, stride/offset semantics and errors remain unchanged.\n\n",
        "Each successful C output owns one [structured value](values.md); inputs are borrowed during the call and failure leaves output pointers untouched. `InterchangeError` uses status13 with its original four-way constructor and full message available through `hmath_last_interchange_error`. Python raises `HMathError` with `interchange_error`. Callbacks may supply the original checked Left by raising `InterchangeError`. Unexpected exceptions abort and are re-raised after cleanup.\n\n",
        "ByteString results are owned `Bytes` objects. `bytes(result)` copies; `result.view()` borrows a read-only span retaining an independent reference. C uses `hmath_bytes_data` while retaining the owner. No terminator is implied. Binary/raw preserve IEEE bits; text follows the source policy and does not promise NaN payload preservation. `boxed=True` on scalar/list decoders retains native typed values when Python scalar conversion is undesirable.\n\n",
        "Element-polymorphic operations select one original fixed-width instance using a scalar/Boolean prototype in C or `dtype=` in Python. Supported types are Bool8, signed/unsigned8/16/32/64, Float32/64 and Complex64/128. Array dtype and requested result type must match as in Haskell. Matrix/Tensor conversions preserve actual element types; they do not route FP32 through FP64. `get_element` returns the original parser program; `run_decoder` executes the original strict decoder, including trailing-byte checks. `put_element` returns the original Put program and `put_bytes` runs it.\n\n",
        "Mapped array access is callback-scoped. A retained mapping capability rejects data reads after scope exit through the original closed-state checks; copied Bytes remain valid. File writes retain the source's IO effects and partial-write behavior. `open_handle`/`close_handle` and seek/tell/flush expose real binary Haskell handles for the original chunked APIs. Handles are shared resources; close them explicitly before releasing their owners.\n\n",
    ]
    mappings = []
    source_names = {e["module"] + "." + e["name"] for e in entries}
    for name, (module, tag) in TYPES.items():
        symbol = "hmath_interchange_" + snake(name) + "_object"
        header.append(f"typedef hmath_value {symbol}; /* kind{tag} */\n")
        if module + "." + name not in source_names:
            mappings.append(
                {
                    "symbol": module + "." + name,
                    "c": [symbol],
                    "python": "hmath.interchange." + name,
                    "specializations": ["original structured type and scoped lifetime"],
                }
            )
    mappings.append(
        {
            "symbol": "HMath.Interchange.Array.Element",
            "c": [
                "hmath_interchange_value_element_type",
                "hmath_interchange_value_get_element",
                "hmath_interchange_value_put_element",
            ],
            "python": "hmath.interchange.Element",
            "specializations": ["all13 original fixed-width Element dictionaries"],
        }
    )
    custom = {
        "elementType": 'def element_type(*, dtype="float64"):\n    return _element_type(dtype)\n',
        "getElement": 'def get_element(endian, *, dtype="float64"):\n    return _get_element(endian,dtype)\n',
        "putElement": 'def put_element(endian,value, *, dtype="float64"):\n    return _put_element(endian,value,dtype)\n',
        "fromValues": 'def from_values(limits,endian,shape,values, *, dtype="float64"):\n    return _from_values(limits,endian,shape,values,dtype)\n',
        "toValues": 'def to_values(array, *, dtype=None, boxed=False):\n    return _to_values("to_values",array,dtype,boxed)\n',
        "toMatrix": 'def to_matrix(array, *, dtype=None):\n    return _to_values("to_matrix",array,dtype,False)\n',
        "toTensor": 'def to_tensor(array, *, dtype=None):\n    return _to_values("to_tensor",array,dtype,False)\n',
        "mappedValue": 'def mapped_value(mapping,indices, *, dtype="float64",boxed=False):\n    return _mapped_value(mapping,indices,dtype,boxed)\n',
    }
    for entry in entries:
        normalized = normalize(entry["signature"])
        parts = split_top(normalized, "->")
        if entry["name"] in OVERRIDES:
            names, types = OVERRIDES[entry["name"]]
        else:
            names, types = argument_names(entry, len(parts) - 1), parts[:-1]
        if entry["name"] == "Limits":
            names = [
                "max_bytes",
                "max_elements",
                "max_rank",
                "max_metadata",
                "max_archive_entries",
            ]
        elif entry["name"] == "RawSpec":
            names = ["dtype", "endian", "order", "shape"]
        elif entry["name"] in (
            "InvalidData",
            "Unsupported",
            "LimitExceeded",
            "InterchangeIOError",
        ):
            names = ["message"]
        specifications = [spec(t) for t in types]
        name = snake(entry["name"])
        source = entry["module"] + "." + entry["name"]
        symbol = "hmath_interchange_value_" + name
        prototype, body = wrapper(symbol, source, names)
        header.append(
            f"/* {source} :: {entry['signature']} */\nHMATH_API {prototype};\n"
        )
        c.append(body)
        if entry["name"] not in SPECIAL:
            q = {
                "Array": "A",
                "Binary": "B",
                "Compression": "C",
                "IO": "I",
                "Numpy": "N",
                "Text": "T",
            }[entry["module"].rsplit(".", 1)[1]]
            hs.append(f'        "{source}"->apply {q}.{entry["name"]} arguments\n')
        if entry["name"] in custom:
            py.append("\n\n" + custom[entry["name"]])
        else:
            boxed = ", *, boxed=False" if entry["name"] == "runDecoder" else ""
            py.append(
                f'\n\ndef {name}({", ".join(names)}{boxed}):\n    """{source} :: {entry["signature"]}."""\n    return _invoke({symbol!r},{specifications!r},[{", ".join(names)}]'
                + (",boxed=boxed" if boxed else "")
                + ")\n"
            )
        mappings.append(
            {
                "symbol": source,
                "c": [symbol],
                "python": "hmath.interchange." + name,
                "specializations": [
                    "all original fixed-width dictionaries where Element-polymorphic; original IO effects and error variants"
                ],
            }
        )
        if entry["name"] in custom:
            python_arguments = custom[entry["name"]].split("(", 1)[1].split("):", 1)[0]
        else:
            python_arguments = ", ".join(names)
            if entry["name"] == "runDecoder":
                python_arguments += ", *, boxed=False"
        docs.append(
            f"## `{name}`\n\n`interchange.{name}({python_arguments})`\n\n{source_prose(entry)}\n\nOriginal: [`{source}`](haskell/{entry['module'].replace('.', '-')}.md#v:{entry['name']}). Python keeps the source argument order; Element-polymorphic helpers use `dtype=` instead of a type annotation.\n\n```haskell\n{entry['signature']}\n```\n\n```c\n{prototype};\n```\n\n"
        )
    auxiliary_docs = {
        "dtype_code": "Return the original DType enumeration code as an integer (Bool8=0 through C128=12).",
        "error_fields": "Return an InterchangeError's original constructor code and full message; embedded NUL and Unicode are retained.",
        "put_bytes": "Execute the original Put program and return owned Bytes. This does not perform file IO.",
        "open_handle": "Open a real binary handle. Modes are rb, wb, ab or r+b; wb truncates and ab appends. IO failures raise the original InterchangeIOError. Close the shared resource explicitly before releasing its value owner.",
        "close_handle": "Close the shared Haskell handle. Other retained owners refer to that same closed resource. Python BinaryHandle.close() closes the resource and releases its own value reference.",
        "seek_handle": "Seek the binary handle with whence 0 (absolute), 1 (relative) or 2 (from end) and an exact integer byte offset. Original handle IO errors become InterchangeIOError.",
        "tell_handle": "Return the handle's current byte position as an exact integer.",
        "flush_handle": "Flush the original Haskell handle. This has the source hFlush contract and does not promise a filesystem durability barrier.",
        "equal_array": "Compare the original Array values, including dtype, endian, layout, metadata and backing bytes. This is structural equality, not a converted numerical comparison.",
    }
    for name, (operation, names) in AUX.items():
        symbol = "hmath_interchange_value_" + name
        prototype, body = wrapper(symbol, operation, names)
        header.append(f"HMATH_API {prototype};\n")
        c.append(body)
        python_specs = (
            [["String"], ["String"]]
            if name == "open_handle"
            else [["Value"] for _ in names]
        )
        py.append(
            f"\n\ndef {name}({', '.join(names)}):\n    return _invoke({symbol!r},{python_specs!r},[{', '.join(names)}])\n"
        )
        docs.append(
            f"## `{name}`\n\n`interchange.{name}({', '.join(names)})`\n\n{auxiliary_docs[name]}\n\n```c\n{prototype};\n```\n\n"
        )
    py.append("\n\nElement = DType\n")
    header.append("#ifdef __cplusplus\n}\n#endif\n#endif\n")
    path = ROOT / "src/HMath/FFI/InterchangeAll.hs"
    haskell = re.sub(
        r"(?<=-- BEGIN GENERATED\n).*?(?=-- END GENERATED)",
        "".join(hs),
        path.read_text(),
        flags=re.DOTALL,
    )
    return {
        "include/hmath_interchange.h": "".join(header),
        "cbits/interchange.c": "".join(c),
        "bindings/python/_hmath_native/interchange.py": "".join(py),
        "bindings/schema/interchange-objects.json": json.dumps(
            {"schema": 1, "bindings": mappings}, indent=2
        )
        + "\n",
        "docs/reference/interchange-bindings.md": "".join(docs),
        "src/HMath/FFI/InterchangeAll.hs": haskell,
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for name, text in generate().items():
        path = ROOT / name
        if args.check:
            if not path.exists() or path.read_text() != text:
                parser.exit(1, "Stale interchange binding: " + name + "\n")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)


if __name__ == "__main__":
    main()
