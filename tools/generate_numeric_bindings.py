"""Generate typed C/Python adapters which call the named Haskell function.

The manifest records concrete specializations, never a replacement formula.
Run with --check in CI to reject stale generated adapters.
"""

import argparse
import json
import keyword
import re
from pathlib import Path

from numeric_specializations import BOUNDED, binding_variants

ROOT = Path(__file__).resolve().parent.parent
PYTHON_MARKER = "# Generated by tools/generate_numeric_bindings.py; do not edit."


def floating(entry):
    return any(a["type"] in ("f", "fs", "p", "c") for a in entry["args"]) or entry[
        "result"
    ] in ("f", "ff", "fff", "ffff", "c", "fs", "fd", "zf", "sf", "sf2", "sf4", "fsf")


def precisions(entry):
    return entry.get("precisions", [32, 64] if floating(entry) else [None])


def prefix(entry):
    return "hmath_" + namespace(entry) + "_" + entry["python"]


def namespace(entry):
    """Keep nested module names distinct in both C and Python namespaces."""
    return entry["module"].removeprefix("HMath.").replace(".", "_").lower()


def module_alias(module):
    return module.removeprefix("HMath.").replace(".", "")


def generate():
    entries = json.loads((ROOT / "bindings/schema/numeric.json").read_text())[
        "functions"
    ]
    # These domains use opaque object/callback adapters owned by separate
    # generators. Reject accidental scalar entries instead of overwriting an
    # independently maintained Python module such as autodiff.py or matrix.py.
    protected = ("HMath.Autodiff", "HMath.Matrix")
    for entry in entries:
        if any(
            entry["module"] == name or entry["module"].startswith(name + ".")
            for name in protected
        ):
            raise ValueError(
                f"Object binding domain cannot use numeric generator: {entry['module']}"
            )
    header = [
        "/* SPDX-License-Identifier: MPL-2.0 */\n",
        "/* Generated by tools/generate_numeric_bindings.py. */\n",
        '#ifndef HMATH_NUMERIC_H\n#define HMATH_NUMERIC_H\n#include "hmath.h"\n',
        '#ifdef __cplusplus\nextern "C" {\n#endif\n',
        "/* Original Haskell semantics, including unchecked NaN/Inf behavior.\n",
        " * Each checked MathError is reported as HMATH_MATH_ERROR with its\n",
        " * constructor and payload in hmath_last_error_message(). Pure errors\n",
        " * return HMATH_HASKELL_EXCEPTION. Output is untouched on failure.\n",
        " * Integer arguments are NUL-terminated ASCII decimal strings; results\n",
        " * are exact decimal strings allocated by HMath. Free each string with\n",
        " * hmath_numeric_string_free, including rational numerator/denominator.\n",
        " * Pair/complex arguments and tuple results are flattened in order.\n",
        " * List output capacity is checked (prefixSum needs count + 1). Pointers must\n",
        " * not overlap one another or inputs. Inputs are borrowed for the call.\n",
        " * Concurrent calls use independent outputs; error state is thread-local.\n",
        " * Cancellation is checked before entry, not during pure evaluation. */\n",
        "HMATH_API void hmath_numeric_string_free(char *value);\n",
        "/* Free owned numerical result arrays (and outer exact-string arrays). */\n",
        "HMATH_API void hmath_numeric_buffer_free(void *value);\n",
        "/* Dynamic results return an owned pointer and logical element count.\n",
        " * Free every exact string first, then the outer buffer. Rational\n",
        " * arrays contain numerator,denominator pairs (2*count strings).\n",
        " * Complex arrays contain real,imaginary pairs (2*count components).\n",
        " * Bounded integer suffixes select the original Haskell numeric\n",
        " * instance: ordinary arithmetic wraps, checked/saturating functions\n",
        " * retain their original checks/clamping. Integer/Rational are exact. */\n",
    ]
    c = [
        "/* SPDX-License-Identifier: MPL-2.0 */\n/* Generated; do not edit. */\n",
        '#include "hmath_numeric.h"\n#include "numeric_internal.h"\n#include <stdlib.h>\n',
        "void hmath_numeric_string_free(char *value) { free(value); }\n",
        "void hmath_numeric_buffer_free(void *value) { free(value); }\n",
    ]
    hs = [
        "{-# LANGUAGE ForeignFunctionInterface #-}\n",
        "-- SPDX-License-Identifier: MPL-2.0\n-- Generated; do not edit.\n",
        "module HMath.FFI.Numeric where\n",
        "import Control.Exception (bracketOnError, evaluate)\nimport Data.Coerce (coerce)\n",
        "import Data.Complex (Complex ((:+)), realPart, imagPart)\n",
        "import Data.Ratio (numerator, denominator, (%))\nimport Foreign\nimport Foreign.C\n",
        "import HMath.FFI.Boundary\n",
    ]
    for module in sorted({e["module"] for e in entries}):
        hs.append(f"import qualified {module} as {module_alias(module)}\n")
    if any(e.get("specializations") for e in entries):
        hs.append(
            '\ncomplexPairs :: [a] -> [Complex a]\ncomplexPairs [] = []\ncomplexPairs (a : b : rest) = (a :+ b) : complexPairs rest\ncomplexPairs _ = error "invalid complex transport"\n'
        )
        hs.append(
            '\nrationalPairs :: [Integer] -> [Rational]\nrationalPairs [] = []\nrationalPairs (a : b : rest) = (a % b) : rationalPairs rest\nrationalPairs _ = error "invalid Rational transport"\n'
        )
    python = {}
    symbols = ["hmath_numeric_string_free", "hmath_numeric_buffer_free"]
    docs = [
        "# Numeric bindings\n\n",
        (
            "These bindings call the original Haskell functions. They do not replace their algorithms or change domain checks. "
            "This is an incremental subset, **not full Haskell API coverage**.\n\n"
        ),
        (
            "Include `hmath_numeric.h` in C/C++; in Python use `from hmath import scalar, basic, trigonometry, statistics, constants`. "
            'Floating functions accept keyword-only `dtype="float64"` or `dtype="float32"`; these select Haskell `Double` and `Float`, respectively. '
            "Functions whose original signature fixes `Double` accept only `float64`; `float32` is rejected rather than silently promoted. "
            "Generic functions may have other Haskell type instances which are not yet bound. "
            "Python returns ordinary floats, complex numbers, tuples, lists, arbitrary-precision integers and `fractions.Fraction` values.\n\n"
        ),
        (
            "Original argument order is preserved. C flattens coordinate pairs and complex values into two real arguments, "
            "lists into a pointer and count, and tuple results into separate output pointers. "
            "Haskell `Int` uses `ptrdiff_t`; `Integer` uses signed ASCII decimal strings without a fixed precision limit. "
            "Rationals use separate exact numerator and denominator strings. Free each returned string with "
            "`hmath_numeric_string_free`. Python owns and releases this transport automatically.\n\n"
        ),
        (
            "Generic Basic, Scalar, Linear and Statistics functions list their supported `dtype` instances below. "
            "`integer` uses unbounded Haskell `Integer`; `rational` uses exact `Rational` and Python `fractions.Fraction`. "
            "`int8`/`int16`/`int32`/`int64` and unsigned `uint*` select the corresponding bounded Haskell types. "
            "`intp`/`uintp` select native-width Haskell `Int`/`Word`. `complex64` and `complex128` select "
            "`Complex Float` and `Complex Double`. Only instances permitted by the original constraints are offered. "
            "[Typed generic Value adapters](numeric-objects.md) additionally preserve bound Numeric.Dual/Quaternion, "
            "original AD.Dual/Expr and supported native Ord labels through their actual dictionaries. "
            "These finite instance sets do not claim support for every user-defined Haskell typeclass instance.\n\n"
            "Ordinary bounded arithmetic keeps the original wrapping behavior; the dedicated checked and saturating "
            "functions keep their original error/clamping behavior. Python rejects values outside the selected bounded "
            "input type with `OverflowError`. Use explicit `dtype='integer'`/`'rational'` for exact arithmetic; existing "
            "floating defaults remain unchanged. Rational input arrays use alternating decimal numerator/denominator "
            "strings; complex arrays use alternating real/imaginary components. Array counts are logical values, "
            "not component counts.\n\n"
        ),
        (
            "A Haskell `Left MathError` becomes `HMATH_MATH_ERROR` (11) in C and `HMathError(status=11)` in Python; "
            "the original constructor and payload are retained in the error message. Pure exceptions use status 6. "
            "Unchecked functions still allow their original NaN/Inf behavior. No finite-value check is added.\n\n"
        ),
        (
            "Input buffers live for the call. Output buffers must not overlap inputs or each other, and list outputs "
            "must hold the input count (plus one for prefixSum); C output capacity is checked. Outputs remain untouched on failure. Initialize the runtime before numerical calls. "
            "Cancellation is checked before the call. Independent calls can run concurrently.\n\n"
        ),
    ]
    for entry in entries:
        module = module_alias(entry["module"])
        group = namespace(entry)
        python.setdefault(
            group,
            [
                f"# SPDX-License-Identifier: MPL-2.0\n{PYTHON_MARKER}\nfrom ._numeric import _call\n"
                + (
                    (
                        "from ._numeric_objects import _call_value, _uses_equality_value\n"
                        if group == "geometry_primitives"
                        else "from ._numeric_objects import _call_value, _uses_value\n"
                    )
                    if group
                    in {
                        "basic",
                        "scalar",
                        "linear",
                        "statistics",
                        "geometry_primitives",
                    }
                    else ""
                )
            ],
        )
        parameters = [
            a["name"] + "_" if keyword.iskeyword(a["name"]) else a["name"]
            for a in entry["args"]
        ]
        default_dtype = entry.get("default_dtype", "float64")
        typed = bool(entry.get("specializations"))
        pyargs = parameters + (
            ["*", f"dtype={default_dtype!r}"] if floating(entry) or typed else []
        )
        source = entry["module"] + "." + entry["name"]
        signature = f"{group}.{entry['python']}({', '.join(pyargs)})"
        if typed:
            variant_map = {
                v["dtype"]: (
                    [a["type"] for a in v["args"]],
                    v["result"],
                    f"float{v['precision']}" if v["precision"] else None,
                    v["suffix"],
                )
                for v in binding_variants(entry)
                if not v["legacy"]
            }
            body = (
                f"    if _uses_value([{', '.join(parameters)}], dtype, ordered={entry['name'] in {'clamp', 'minimumScalar', 'maximumScalar'}}):\n"
                f"        return _call_value({prefix(entry)!r}, {[a['type'] for a in entry['args']]!r}, [{', '.join(parameters)}], dtype)\n"
                "    variants = {\n"
                + "".join(
                    f"        {dtype!r}: {spec!r},\n"
                    for dtype, spec in variant_map.items()
                )
                + "    }\n"
                "    if dtype not in variants:\n        raise ValueError('unsupported dtype for this Haskell function')\n"
                "    kinds, result, precision, suffix = variants[dtype]\n"
                f"    return _call({prefix(entry)!r}, kinds, result, [{', '.join(parameters)}], precision, {entry.get('result_extra', 0)}, symbol_suffix=suffix)\n"
            )
        else:
            body = (
                (
                    '    if dtype != "float64":\n        raise ValueError("this Haskell function uses Double; dtype must be \'float64\'")\n'
                    if precisions(entry) == [64]
                    else ""
                )
                + "    return _call(\n"
                f"        {prefix(entry)!r},\n"
                f"        {[a['type'] for a in entry['args']]!r},\n"
                f"        {entry['result']!r},\n"
                f"        [{', '.join(parameters)}],\n"
                f"        {'dtype' if floating(entry) else 'None'},\n"
                f"        {entry.get('result_extra', 0)},\n"
                "    )\n"
            )
        if entry["module"] == "HMath.Geometry.Primitives" and entry["name"] in {
            "hammingDistance",
            "jaccardDistance",
        }:
            body = (
                f"    if _uses_equality_value([{', '.join(parameters)}], dtype):\n"
                f"        return _call_value({prefix(entry)!r}, {[a['type'] for a in entry['args']]!r}, [{', '.join(parameters)}], dtype)\n"
            ) + body
        python[group].append(
            f"\n\ndef {entry['python']}({', '.join(pyargs)}):\n"
            f'    """Call {source}; preserve its argument order, result and errors."""\n'
            + body
        )
        docs.append(f"## `{group}.{entry['python']}`\n\n`{signature}`\n\n")
        docs.append(
            f"Original: [`{source}`](haskell/{entry['module'].replace('.', '-')}.md#v:{entry['name']}). "
            "The linked contract defines the operation, valid inputs, result and mathematical errors.\n\n"
        )
        if typed:
            docs.append(
                "Supported `dtype`: "
                + ", ".join(f"`{name}`" for name in entry["specializations"])
                + ".\n\n"
            )
        source_entry = entry
        for variant in binding_variants(source_entry):
            entry = dict(source_entry, args=variant["args"], result=variant["result"])
            precision = variant["precision"]
            ct, ht, native = (
                ("float", "CFloat", "Float")
                if precision == 32
                else ("double", "CDouble", "Double")
            )
            symbol = prefix(entry) + variant["suffix"]
            internal = symbol.replace("hmath_", "hm_numeric_", 1)
            hsname = "ffi" + "".join(part.title() for part in symbol.split("_")[1:])
            symbols.append(symbol)
            ca, ha, names, reads, arguments, validations = [], [], [], [], [], []
            for arg in entry["args"]:
                name, kind = arg["name"], arg["type"]
                # Prefix Haskell variables to avoid name clashes with imported APIs.
                var = "v" + name[0].upper() + name[1:]
                if kind in BOUNDED:
                    ctype, htype = BOUNDED[kind][:2]
                    ca.append(f"{ctype} {name}")
                    ha.append(htype)
                    names.append(var)
                    arguments.append(f"({var} :: {htype})")
                elif kind.endswith("s") and kind[:-1] in BOUNDED:
                    ctype, htype = BOUNDED[kind[:-1]][:2]
                    ca.extend([f"const {ctype} *{name}", f"size_t {name}_count"])
                    ha.extend([f"Ptr {htype}", "CSize"])
                    names.extend([var, var + "Count"])
                    reads.append(
                        f"    {var}Value <- peekArray (fromIntegral {var}Count) {var}\n"
                    )
                    arguments.append(var + "Value")
                    validations.append(
                        f'    if ({name}_count > (size_t)PTRDIFF_MAX / sizeof({ctype})) return hm_error(HMATH_OVERFLOW, "list byte span exceeds ptrdiff_t");\n'
                    )
                    validations.append(
                        f'    if ({name}_count && !{name}) return hm_error(HMATH_INVALID_ARGUMENT, "NULL list input");\n'
                    )
                elif kind in ("cs", "qs"):
                    element_c, element_h = (
                        (ct, ht) if kind == "cs" else ("const char *", "CString")
                    )
                    ca.extend([f"{element_c} const *{name}", f"size_t {name}_count"])
                    ha.extend([f"Ptr {element_h}", "CSize"])
                    names.extend([var, var + "Count"])
                    validations.append(
                        f'    if ({name}_count > (size_t)PTRDIFF_MAX / (2 * sizeof({element_c}))) return hm_error(HMATH_OVERFLOW, "paired list byte span exceeds ptrdiff_t");\n'
                    )
                    validations.append(
                        f'    if ({name}_count && !{name}) return hm_error(HMATH_INVALID_ARGUMENT, "NULL paired list input");\n'
                    )
                    if kind == "cs":
                        reads.append(
                            f"    {var}Raw <- peekArray (2 * fromIntegral {var}Count) (castPtr {var} :: Ptr {native})\n"
                        )
                        reads.append(f"    let {var}Value = complexPairs {var}Raw\n")
                    else:
                        validations.append(
                            f"    for (size_t i = 0; i < 2 * {name}_count; ++i) {{\n        if (!hm_decimal({name}[i])) return hm_error(HMATH_INVALID_ARGUMENT, \"invalid Rational list component\");\n        if (i % 2) {{\n            const char *digit = {name}[i];\n            if (*digit == '-') ++digit;\n            while (*digit == '0') ++digit;\n            if (!*digit) return hm_error(HMATH_INVALID_ARGUMENT, \"zero Rational list denominator\");\n        }}\n    }}\n"
                        )
                        reads.append(
                            f"    {var}Raw <- peekArray (2 * fromIntegral {var}Count) {var} >>= mapM readInteger\n"
                        )
                        reads.append(f"    let {var}Value = rationalPairs {var}Raw\n")
                    arguments.append(var + "Value")
                elif kind == "f":
                    ca.append(f"{ct} {name}")
                    ha.append(ht)
                    names.append(var)
                    arguments.append(f"(coerce {var} :: {native})")
                elif kind == "i":
                    ca.append(f"ptrdiff_t {name}")
                    ha.append("CPtrdiff")
                    names.append(var)
                    arguments.append(f"(fromIntegral {var})")
                elif kind == "b":
                    ca.append(f"int {name}")
                    ha.append("CInt")
                    names.append(var)
                    arguments.append(f"({var} /= 0)")
                elif kind == "z":
                    ca.append(f"const char *{name}")
                    ha.append("CString")
                    names.append(var)
                    reads.append(f"    {var}Value <- readInteger {var}\n")
                    arguments.append(var + "Value")
                    validations.append(
                        f'    if (!hm_decimal({name})) return hm_error(HMATH_INVALID_ARGUMENT, "{name}: expected signed decimal Integer");\n'
                    )
                elif kind == "q":
                    ca.extend(
                        [
                            f"const char *{name}_numerator",
                            f"const char *{name}_denominator",
                        ]
                    )
                    ha.extend(["CString", "CString"])
                    names.extend([var + "Numerator", var + "Denominator"])
                    reads.extend(
                        [
                            f"    {var}N <- readInteger {var}Numerator\n",
                            f"    {var}D <- readInteger {var}Denominator\n",
                        ]
                    )
                    arguments.append(f"({var}N % {var}D)")
                    validations.append(
                        f'    if (!hm_decimal({name}_numerator) || !hm_decimal({name}_denominator)) return hm_error(HMATH_INVALID_ARGUMENT, "invalid Rational decimal components");\n'
                    )
                    validations.append(
                        f"    const char *{name}_digit = {name}_denominator;\n    if (*{name}_digit == '-') ++{name}_digit;\n    while (*{name}_digit == '0') ++{name}_digit;\n    if (!*{name}_digit) return hm_error(HMATH_INVALID_ARGUMENT, \"zero Rational denominator\");\n"
                    )
                elif kind in ("p", "c"):
                    ca.extend([f"{ct} {name}_0", f"{ct} {name}_1"])
                    ha.extend([ht, ht])
                    names.extend([var + "0", var + "1"])
                    first, second = (
                        f"(coerce {var}0 :: {native})",
                        f"(coerce {var}1 :: {native})",
                    )
                    arguments.append(
                        f"({first}, {second})"
                        if kind == "p"
                        else f"({first} :+ {second})"
                    )
                elif kind == "fs":
                    ca.extend([f"const {ct} *{name}", f"size_t {name}_count"])
                    ha.extend([f"Ptr {ht}", "CSize"])
                    names.extend([var, var + "Count"])
                    reads.append(
                        f"    {var}Value <- peekArray (fromIntegral {var}Count) (castPtr {var} :: Ptr {native})\n"
                    )
                    arguments.append(var + "Value")
                    validations.append(
                        f'    if ({name}_count > (size_t)PTRDIFF_MAX / sizeof({ct})) return hm_error(HMATH_OVERFLOW, "list byte span exceeds ptrdiff_t");\n'
                    )
                    validations.append(
                        f'    if ({name}_count && !{name}) return hm_error(HMATH_INVALID_ARGUMENT, "NULL list input");\n'
                    )
                elif kind in ("zs", "is"):
                    element_c, element_h = (
                        ("const char *", "CString")
                        if kind == "zs"
                        else ("ptrdiff_t", "CPtrdiff")
                    )
                    ca.extend([f"{element_c} const *{name}", f"size_t {name}_count"])
                    ha.extend([f"Ptr {element_h}", "CSize"])
                    names.extend([var, var + "Count"])
                    reads.append(
                        f"    {var}Raw <- peekArray (fromIntegral {var}Count) {var}\n"
                    )
                    reads.append(
                        f"    {var}Value <- mapM readInteger {var}Raw\n"
                        if kind == "zs"
                        else f"    let {var}Value = map fromIntegral {var}Raw\n"
                    )
                    arguments.append(var + "Value")
                    validations.append(
                        f'    if ({name}_count > (size_t)PTRDIFF_MAX / sizeof({element_c}) || ({name}_count && !{name})) return hm_error(HMATH_INVALID_ARGUMENT, "invalid list input span");\n'
                    )
                    if kind == "zs":
                        validations.append(
                            f'    for (size_t i = 0; i < {name}_count; ++i) if (!hm_decimal({name}[i])) return hm_error(HMATH_INVALID_ARGUMENT, "invalid Integer list element");\n'
                        )
                    validations.append(
                        f'    if ({name}_count && !{name}) return hm_error(HMATH_INVALID_ARGUMENT, "NULL list input");\n'
                    )
                else:
                    raise ValueError(kind)
            result = entry["result"]
            if result in ("fd", "zd", "id", "qd", "cd") or (
                result.endswith("d") and result[:-1] in BOUNDED
            ):
                result_types = {
                    "fd": (ct, ht),
                    "cd": (ct, ht),
                    "zd": ("char *", "CString"),
                    "id": ("ptrdiff_t", "CPtrdiff"),
                    "qd": ("char *", "CString"),
                }
                result_types.update(
                    {name + "d": spec[:2] for name, spec in BOUNDED.items()}
                )
                element_c, element_h = result_types[result]
                ca.extend([f"{element_c} **out_data", "size_t *out_count"])
                ha.extend([f"Ptr (Ptr {element_h})", "Ptr CSize"])
                names.extend(["outData", "outCount"])
                validations.append(
                    '    if (!out_data || !out_count) return hm_error(HMATH_INVALID_ARGUMENT, "NULL dynamic output");\n'
                )
                csig = (
                    f"hmath_status {symbol}(\n    "
                    + ",\n    ".join(["hmath_context *context"] + ca)
                    + ")"
                )
                header.append(
                    f"/* {source}; owned array result. */\nHMATH_API {csig};\n"
                )
                docs.append(f"```c\n{csig};\n```\n\n")
                c.append(
                    f"extern int {internal}(\n    "
                    + ",\n    ".join(ca)
                    + f");\n{csig} {{\n"
                )
                c.extend(validations)
                c.append(
                    "    hmath_status status = hm_enter(context);\n    if (status) return status;\n"
                )
                cnames = [item.rsplit(" ", 1)[-1].lstrip("*") for item in ca]
                c.append(
                    f"    status = (hmath_status){internal}({', '.join(cnames)});\n    hm_leave();\n    return status;\n}}\n"
                )
                hsig = "\n    " + " ->\n    ".join(ha + ["IO CInt"])
                hs.append(
                    f'\nforeign export ccall "{internal}" {hsname} :: {hsig}\n{hsname} :: {hsig}\n'
                )
                hs.append(f"{hsname} {' '.join(names)} = boundary $ do\n")
                hs.extend(reads)
                call = f"{module}.{entry['name']} " + " ".join(arguments)
                wrapped = call if entry["checked"] else f"Right ({call})"
                hs.append(f"    checked ({wrapped}) $ \\value -> do\n")
                if result in ("fd", "id", "cd") or result[:-1] in BOUNDED:
                    element_native = (
                        native
                        if result in ("fd", "cd")
                        else "Int"
                        if result == "id"
                        else BOUNDED[result[:-1]][1]
                    )
                    expression = (
                        "concatMap (\\z -> [realPart z, imagPart z]) value"
                        if result == "cd"
                        else "value"
                    )
                    hs.append(
                        f"        strict <- mapM evaluate ({expression} :: [{element_native}])\n"
                    )
                    values = (
                        f"map (coerce :: {native} -> {ht}) strict"
                        if result in ("fd", "cd")
                        else "map (fromIntegral :: Int -> CPtrdiff) strict"
                        if result == "id"
                        else "strict"
                    )
                    hs.append(
                        f"        bracketOnError (newArray ({values})) free $ \\pointer -> do\n            poke outData pointer\n            poke outCount (fromIntegral (length {'value' if result == 'cd' else 'strict'}))\n"
                    )
                else:
                    texts = (
                        "map show value"
                        if result == "zd"
                        else "concatMap (\\r -> [show (numerator r), show (denominator r)]) value"
                    )
                    hs.append(
                        f"        writeStrings ({texts}) $ \\textPointers ->\n            bracketOnError (newArray textPointers) free $ \\pointer -> do\n                poke outData pointer\n                poke outCount (fromIntegral (length value))\n"
                    )
                continue
            output_kinds = {
                "f": ["f"],
                "ff": ["f", "f"],
                "fff": ["f"] * 3,
                "ffff": ["f"] * 4,
                "sf": ["f"] * 2,
                "sf2": ["f"] * 4,
                "sf4": ["f"] * 8,
                "fsf": ["f"] * 3,
                "c": ["f", "f"],
                "b": ["b"],
                "z": ["z"],
                "zz": ["z", "z"],
                "zzz": ["z"] * 3,
                "zzzz": ["z"] * 4,
                "i": ["i"],
                "q": ["z", "z"],
                "zf": ["z", "f"],
                "fs": ["fs"],
            }
            output_kinds.update({name: [name] for name in BOUNDED})
            outs = output_kinds[result]
            output_values = {
                "f": ["value"],
                "b": ["value"],
                "i": ["value"],
                "z": ["value"],
                "ff": ["first", "second"],
                "zz": ["first", "second"],
                "zf": ["first", "second"],
                "fff": ["first", "second", "third"],
                "ffff": ["first", "second", "third", "fourth"],
                "zzz": ["first", "second", "third"],
                "sf": ["Special.sfValue value", "Special.sfError value"],
                "sf2": [
                    "Special.sfValue first",
                    "Special.sfError first",
                    "Special.sfValue second",
                    "Special.sfError second",
                ],
                "sf4": [
                    f"Special.{field} {name}"
                    for name in ("first", "second", "third", "fourth")
                    for field in ("sfValue", "sfError")
                ],
                "fsf": ["first", "Special.sfValue second", "Special.sfError second"],
                "zzzz": ["first", "second", "third", "fourth"],
                "c": ["realPart value", "imagPart value"],
                "q": ["numerator value", "denominator value"],
                "fs": ["value"],
            }
            output_values.update({name: ["value"] for name in BOUNDED})
            values = output_values[result]
            pattern = {
                "sf2": "(first, second)",
                "sf4": "(first, second, third, fourth)",
                "fsf": "(first, second)",
            }.get(result) or (
                "value"
                if result not in ("ff", "fff", "ffff", "zz", "zzz", "zzzz", "zf")
                else "(" + ", ".join(values) + ")"
            )
            forces, pokes, strings = [], [], []
            for index, (kind, expression) in enumerate(zip(outs, values)):
                name = f"out{index}"
                ca.append(
                    {
                        "f": f"{ct} *",
                        "b": "int *",
                        "i": "ptrdiff_t *",
                        "z": "char **",
                        "fs": f"{ct} *",
                        **{key: spec[0] + " *" for key, spec in BOUNDED.items()},
                    }[kind]
                    + name
                )
                ha.append(
                    {
                        "f": f"Ptr {ht}",
                        "b": "Ptr CInt",
                        "i": "Ptr CPtrdiff",
                        "z": "Ptr CString",
                        "fs": f"Ptr {ht}",
                        **{key: f"Ptr {spec[1]}" for key, spec in BOUNDED.items()},
                    }[kind]
                )
                names.append(name)
                if kind == "fs":
                    length_name = (
                        next(a["name"] for a in entry["args"] if a["type"] == "fs")
                        + "_count"
                    )
                    extra = entry.get("result_extra", 0)
                    ca.append("size_t out_capacity")
                    ha.append("CSize")
                    names.append("_outCapacity")
                    validations.append(
                        f'    if ({length_name} + {extra} > (size_t)PTRDIFF_MAX / sizeof({ct})) return hm_error(HMATH_OVERFLOW, "output byte span exceeds ptrdiff_t");\n'
                    )
                    validations.append(
                        f'    if (out_capacity < {length_name} + {extra}) return hm_error(HMATH_BOUNDS_ERROR, "insufficient output capacity");\n'
                    )
                    validations.append(
                        f'    if (({length_name} + {extra}) && !{name}) return hm_error(HMATH_INVALID_ARGUMENT, "NULL list output");\n'
                    )
                    forces.append(
                        f"        strict{index} <- mapM evaluate {expression}\n"
                    )
                    # mapM completes every element before pokeArray starts.
                    pokes.append(
                        f"            pokeArray (castPtr {name} :: Ptr {native}) strict{index}\n"
                    )
                else:
                    validations.append(
                        f'    if (!{name}) return hm_error(HMATH_INVALID_ARGUMENT, "NULL output");\n'
                    )
                    if kind == "z":
                        strings.append(f"show ({expression})")
                        pokes.append(
                            f"            poke {name} (textPointers !! {len(strings) - 1})\n"
                        )
                    else:
                        forces.append(
                            f"        strict{index} <- evaluate ({expression})\n"
                        )
                        val = (
                            f"(coerce strict{index} :: {ht})"
                            if kind == "f"
                            else f"(coerce strict{index} :: {BOUNDED[kind][1]})"
                            if kind in BOUNDED
                            else f"(fromIntegral strict{index})"
                            if kind == "i"
                            else f"(if strict{index} then 1 else 0)"
                        )
                        pokes.append(f"            poke {name} {val}\n")
            csig = (
                f"hmath_status {symbol}(\n    "
                + ",\n    ".join(["hmath_context *context"] + ca)
                + ")"
            )
            header.append(
                f"/* {source}; {variant['dtype'] or 'fixed'} specialization. */\nHMATH_API {csig};\n"
            )
            docs.append(f"```c\n{csig};\n```\n\n")
            c.append(
                f"extern int {internal}(\n    "
                + ",\n    ".join(ca)
                + f");\n{csig} {{\n"
            )
            c.extend(validations)
            c.append(
                "    hmath_status status = hm_enter(context);\n    if (status) return status;\n"
            )
            cnames = [item.rsplit(" ", 1)[-1].lstrip("*") for item in ca]
            c.append(
                f"    status = (hmath_status){internal}({', '.join(cnames)});\n    hm_leave();\n    return status;\n}}\n"
            )
            hsig = "\n    " + " ->\n    ".join(ha + ["IO CInt"])
            hs.append(
                f'\nforeign export ccall "{internal}" {hsname} :: {hsig}\n{hsname} :: {hsig}\n'
            )
            hs.append(f"{hsname} {' '.join(names)} = boundary $ do\n")
            hs.extend(reads)
            call = f"{module}.{entry['name']}" + (
                "\n        " + "\n        ".join(arguments) if arguments else ""
            )
            wrapped = call if entry["checked"] else f"Right ({call})"
            # Concrete annotation is required for no-argument constants.
            if not entry["args"]:
                wrapped = f"Right ({call} :: {native})"
            hs.append(f"    checked ({wrapped}) $ \\{pattern} -> do\n")
            hs.extend(forces)
            if strings:
                hs.append(
                    f"        writeStrings [{', '.join(strings)}] $ \\textPointers -> do\n"
                )
                hs.extend(pokes)
            else:
                hs.extend(line[4:] for line in pokes)
    header.append("#ifdef __cplusplus\n}\n#endif\n#endif\n")
    outputs = {
        "include/hmath_numeric.h": "".join(header),
        "cbits/numeric_generated.c": re.sub(
            r"    if \((.+)\) return (.+);",
            r"    if (\1)\n        return \2;",
            "".join(c),
        ),
        "src/HMath/FFI/Numeric.hs": "".join(hs),
        "docs/reference/numeric-bindings.md": "".join(docs),
        "bindings/schema/numeric-symbols.txt": "\n".join(symbols) + "\n",
    }
    outputs.update(
        {
            f"bindings/python/_hmath_native/{group}.py": "".join(lines)
            for group, lines in python.items()
        }
    )
    outputs["bindings/python/_hmath_native/_numeric_modules.py"] = (
        f"# SPDX-License-Identifier: MPL-2.0\n{PYTHON_MARKER}\n\n"
        "NUMERIC_MODULES = (\n"
        + "".join(f"    {name!r},\n" for name in sorted(python))
        + ")\n"
    )
    if "special" in python:
        outputs["bindings/python/_hmath_native/special.py"] = outputs[
            "bindings/python/_hmath_native/special.py"
        ].replace(
            "from ._numeric import _call", "from ._numeric import SFResult, _call"
        )
        outputs["bindings/python/_hmath_native/special.py"] += (
            "\n\n__all__ = "
            + repr(
                sorted(
                    [e["python"] for e in entries if e["module"] == "HMath.Special"]
                    + ["SFResult"]
                )
            )
            + "\n"
        )
    for group, extension in {
        "units": "units_values",
        "random": "random_values",
        "probability": "probability_values",
        "statistics_advanced": "statistics_values",
        "signal": "signal_values",
        "fourier": "fourier_values",
        "interpolation": "interpolation_values",
        "datastructure": "data_structures",
        "discrete": "discrete_values",
        "algorithms": "algorithm_values",
        "combinatorics": "combinatorics_values",
        "tensor": "_tensor_core",
        "deeplearning_core": "_neural_core",
        "deeplearning_precision": "_neural_precision",
        "deeplearning_metrics": "_neural_metrics",
        "complex": "complex_extras",
        "trigonometry": "trigonometry_extras",
        "numbertheory": "numbertheory_extras",
        "special": "special_extras",
    }.items():
        if group in python:
            outputs[f"bindings/python/_hmath_native/{group}.py"] += (
                f"\n\nfrom .{extension} import *\n"
            )
            if group == "special":
                outputs["bindings/python/_hmath_native/special.py"] += (
                    "\n__all__.extend(['sf_error', 'sf_result', 'sf_value'])\n"
                )
    return outputs


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    stale = []
    outputs = generate()
    protected = {"autodiff.py", "matrix.py", "optimization.py"}
    owned_directory = ROOT / "bindings/python/_hmath_native"
    for path in owned_directory.glob("*.py"):
        if path.name in protected or str(path.relative_to(ROOT)) in outputs:
            continue
        text = path.read_text()
        owned = PYTHON_MARKER in text
        legacy_owned = (
            "# Generated; do not edit." in text
            and "from ._numeric import _call\n" in text
        )
        if owned or legacy_owned:
            if args.check:
                stale.append(str(path.relative_to(ROOT)))
            else:
                path.unlink()
    for name, text in outputs.items():
        path = ROOT / name
        if args.check:
            if not path.exists() or path.read_text() != text:
                stale.append(name)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
    if stale:
        parser.exit(1, "Stale generated bindings: " + ", ".join(stale) + "\n")


if __name__ == "__main__":
    main()
