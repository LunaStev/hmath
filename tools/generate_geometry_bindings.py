ROOT = Path(__file__).resolve().parent.parent
TYPE_NAMES = [
    "Point2",
    "Point3",
    "PointND",
    "Line",
    "Ray",
    "Segment",
    "Plane",
    "Triangle",
    "Rectangle",
    "Circle",
    "Ellipse",
    "Polygon",
    "Sphere",
    "AABB",
    "OBB",
    "Capsule",
    "Cylinder",
    "Cone",
    "Frustum",
    "Orientation",
    "Location",
    "Penetration",
    "HullAlgorithm",
    "BooleanOperation",
    "Metric",
    "Intersection2",
    "CircleIntersection",
    "SpatialKind",
    "PointCloud",
    "SpatialIndex",
    "NeighborQuery",
]
TYPES = {name: 169 + index for index, name in enumerate(TYPE_NAMES)}
KNOWN = {*TYPES, "Matrix Double", "IndexedTriangle", "Ordering"}
SKIP = {"hammingDistance", "jaccardDistance"}


def entries():
    data = json.loads((ROOT / "bindings/schema/geometry-functions.json").read_text())[
        "functions"
    ]
    return [e for e in data if e["name"] not in SKIP]


def arguments(entry):
    types = split_top(entry["signature"], "->")[:-1]
    result = []
    used = set()
    for typ in types:
        name = {
            "Double": "number",
            "Int": "count",
            "Bool": "flag",
            "Matrix Double": "matrix",
        }.get(
            typ,
            "values"
            if typ.startswith("[")
            else "tuple_value"
            if typ.startswith("(")
            else snake(typ),
        )
        if keyword.iskeyword(name) or name in {
            "operator",
            "union",
            "struct",
            "class",
            "template",
        }:
            name += "Value"
        original = name
        index = 2
        while name in used:
            name = original + str(index)
            index += 1
        used.add(name)
        result.append(name)
    return result


def public_name(entry):
    # The public raw PointND constructor and checked pointND function are distinct.
    return "point_nd_raw" if entry["name"] == "PointND" else snake(entry["name"])


def result_type(signature):
    result = split_top(signature, "->")[-1]
    checked = result.startswith("Either MathError ")
    result = result.removeprefix("Either MathError ")
    while result.startswith("(") and result.endswith(")"):
        inner = result[1:-1].strip()
        if len(split_top(inner, ",")) != 1:
            break
        result = inner
    return result, checked


def native_type(typ):
    if typ.startswith("["):
        return "[" + native_type(typ[1:-1]) + "]"
    if typ.startswith("("):
        return "(" + ",".join(native_type(x) for x in split_top(typ[1:-1], ",")) + ")"
    if typ.startswith("Maybe "):
        return "(Maybe " + native_type(typ[6:].strip()) + ")"
    if typ == "Matrix Double":
        return "(M.Matrix Double)"
    return "G." + typ if typ in KNOWN else typ


HS_PREFIX = """{-# LANGUAGE ForeignFunctionInterface #-}
-- SPDX-License-Identifier: MPL-2.0
-- Generated by tools/generate_geometry_bindings.py.
module HMath.FFI.Geometry where
import Foreign
import Foreign.C
import Data.Typeable (cast)
import HMath.FFI.Boundary
import HMath.FFI.Coefficient (ScalarType (SDouble))
import HMath.FFI.GraphCodec (Wire(..),boxed,unboxed)
import HMath.FFI.Value
import qualified HMath.Geometry as G
import qualified HMath.Matrix as M

matrixValue :: M.Matrix Double -> Value
matrixValue = Dense . SomeMatrix SDouble
matrixInput :: Value -> IO (M.Matrix Double)
matrixInput (Dense (SomeMatrix _ value)) = maybe (invalid "Matrix Double required") pure (cast value)
matrixInput _ = invalid "dense Matrix Double required"
orderingValue :: Ordering -> Value
orderingValue value = Index (case value of LT -> -1;EQ -> 0;GT -> 1)
-- Outer presence must remain explicit: Nothing and Just Nothing are distinct.
nestedMaybeValue :: Wire a => Maybe (Maybe a) -> Value
nestedMaybeValue Nothing = Tuple [Boolean False,None]
nestedMaybeValue (Just value) = Tuple [Boolean True,wire value]
"""


def generate():
    data = entries()
    known = {
        e["symbol"]
        for e in json.loads((ROOT / "bindings/schema/public-api.json").read_text())[
            "symbols"
        ]
    }
    for e in data:
        assert e["module"] + "." + e["name"] in known, e
    header = [
        '/* SPDX-License-Identifier: MPL-2.0 */\n/* Generated by tools/generate_geometry_bindings.py. */\n#ifndef HMATH_GEOMETRY_H\n#define HMATH_GEOMETRY_H\n#include "hmath_value.h"\n#ifdef __cplusplus\nextern "C" {\n#endif\n',
        "/* Actual immutable Geometry objects use kinds169..199. Inputs are borrowed;\n * successful outputs transfer one owned Value, unchanged on failure. Release\n * with hmath_value_release; each live owner pins the runtime. Source shape,\n * coordinate1e50, work/iteration budgets, exact Rational predicates and original\n * Double results are preserved. Raw public constructors remain unchecked;\n * checked operations retain their original validation and MathError/status11.\n * Matrices are shared Dense Matrix Double values. IndexedTriangle is an Int\n * triple. Ordering is a Haskell Int value -1(LT),0(EQ),1(GT). Other lists, tuples\n * and optional values retain source structure; nested Maybe results explicitly\n * return Tuple(Bool outer_present, inner_optional), distinguishing coincidence\n * from no intersection. Readers retain independent references per thread. */\n",
    ]
    c = [
        '/* SPDX-License-Identifier: MPL-2.0 */\n/* Generated by tools/generate_geometry_bindings.py. */\n#include "hmath_geometry.h"\n#include "value_internal.h"\nextern int hm_geometry_apply(int,void *const *,size_t,void **);\n'
    ]
    hs = [HS_PREFIX]
    for typ, tag in TYPES.items():
        hs.append(
            "instance Wire G."
            + typ
            + " where\n    wire = boxed "
            + str(tag)
            + "\n    unwire = unboxed "
            + str(tag)
            + "\n"
        )
    hs.insert(0, "{-# OPTIONS_GHC -Wno-orphans #-}\n")
    py = [
        '# SPDX-License-Identifier: MPL-2.0\n# Generated by tools/generate_geometry_bindings.py; do not edit.\n"""Original checked geometry, topology, intersections and spatial search."""\nfrom ._geometry_base import GeometryValue, Ordering, _invoke\nfrom ._value import register\nfrom .geometry_primitives import hamming_distance, jaccard_distance\n\nIndexedTriangle = tuple\n'
    ]
    exports = [
        "IndexedTriangle",
        "Ordering",
        "hamming_distance",
        "jaccard_distance",
        "parts",
        "describe",
    ]
    docs = [
        "# Geometry bindings\n\n`from hmath import geometry` calls the original checked geometry algorithms. C includes `hmath_geometry.h`. Coordinates retain their finite1e50 cap, ND dimension1..16 bounds, exact Rational orientation/incircle predicates, source algorithm budgets, tie order and Double outputs. Raw public constructors retain their unchecked behavior; checked operations validate them without adapter changes.\n\nObjects are immutable owned [structured values](values.md); inputs are borrowed for a synchronous call and success transfers one output reference. Outputs stay untouched on failure. Each live owner pins the runtime. Independent readers retain their own references; original MathError/status11 includes its complete constructor and payload. Cancellation is checked before entry.\n\nUse `parts(value)` or `value.parts` for a public data constructor: it returns `(constructor_name, tuple_of_fields)` with typed child owners. A child remains valid after its parent closes. `value.coordinates` returns coordinates for Point2/Point3/PointND. Abstract PointCloud/SpatialIndex remain abstract; their original query functions are available. `describe(value)` exposes the original Show representation for inspection, without parsing or dispatching mathematics through text.\n\n`line_plane_intersection` and `plane_intersection` return `(outer_present, inner_optional)`: `(False, None)` is no intersection, `(True, None)` is coincidence, `(True, value)` is one intersection. This preserves all three source `Maybe (Maybe a)` states. `incircle` returns `Ordering.LT/EQ/GT` (C Haskell-Int values -1/0/1). Indexed triangles remain tuples of three zero-based original input indices. Matrix operations exchange actual shared `Matrix Double` objects.\n\nPolygon Boolean rings retain exterior/hole orientation. Constraints in Delaunay triangulation do not become a polygon/hole specification. Nearest-neighbor results keep original IDs, distance/ID tie order and explicit budget/exhaustive fields. Collision/penetration error estimates retain their source meaning; transforms retain the documented OpenGL depth conventions.\n\nThe existing hamming/jaccard compatibility functions expose Float/Double numeric variants; they do not claim arbitrary user-defined Haskell Eq instances.\n\n"
    ]
    mappings = []
    symbols = []
    names = {e["name"] for e in data}
    for typ, tag in TYPES.items():
        py.append(
            "\n\nclass "
            + typ
            + '(GeometryValue):\n    """Actual immutable HMath.Geometry.'
            + typ
            + ' native owner."""\n\n\nregister('
            + str(tag)
            + ", "
            + typ
            + ")\n"
        )
        exports.append(typ)
        header.append(
            "typedef hmath_value hmath_geometry_"
            + snake(typ)
            + "_object; /* kind"
            + str(tag)
            + " */\n"
        )
        if typ not in names:
            source = next(
                e["symbol"]
                for e in json.loads(
                    (ROOT / "bindings/schema/public-api.json").read_text()
                )["symbols"]
                if e["symbol"].startswith("HMath.Geometry.")
                and e["symbol"].rsplit(".", 1)[-1] == typ
            )
            mappings.append(
                {
                    "symbol": source,
                    "c": ["hmath_geometry_" + snake(typ) + "_object"],
                    "python": "hmath.geometry." + typ,
                    "specializations": ["original opaque type"],
                }
            )
    header.append(
        "typedef hmath_value hmath_geometry_indexed_triangle_object; /* tuple(Int,Int,Int) */\n"
    )
    mappings.append(
        {
            "symbol": "HMath.Geometry.Triangulation.IndexedTriangle",
            "c": ["hmath_geometry_indexed_triangle_object"],
            "python": "hmath.geometry.IndexedTriangle",
            "specializations": ["exact original Int triple"],
        }
    )
    for helper in ["parts", "describe", "equal"]:
        arity = 2 if helper == "equal" else 1
        prototype = (
            "hmath_status hmath_geometry_"
            + helper
            + "(hmath_context *context"
            + "".join(",const hmath_value *value" + str(k) for k in range(arity))
            + ",hmath_value **out)"
        )
        header.append("HMATH_API " + prototype + ";\n")
        c.append(
            "extern int hm_geometry_"
            + helper
            + "("
            + ",".join(["void *"] * arity + ["void **"])
            + ");\n"
            + prototype
            + " {\n    if(!out"
            + "".join(" || !value" + str(k) for k in range(arity))
            + ')return hm_error(HMATH_INVALID_ARGUMENT,"NULL geometry helper argument");\n    hmath_value *temporary=NULL;\n    hmath_status status=hm_value_begin(context,&temporary);\n    if(status)return status;\n    return hm_value_finish(temporary,hm_geometry_'
            + helper
            + "("
            + ",".join("hm_value_stable(value" + str(k) + ")" for k in range(arity))
            + ",&temporary->stable),out);\n}\n"
        )
        symbols.append("hmath_geometry_" + helper)
    hs.append(
        'foreign export ccall "hm_geometry_describe" describe :: StablePtr Value -> Ptr (StablePtr Value) -> IO CInt\ndescribe :: StablePtr Value -> Ptr (StablePtr Value) -> IO CInt\ndescribe input out = boundary $ do\n    value <- deRefStablePtr input\n    text <- case valueInfo value of\n'
    )
    for typ, tag in TYPES.items():
        hs.append(
            "        ("
            + str(tag)
            + ",_,_) -> show <$> (unwire value :: IO G."
            + typ
            + ")\n"
        )
    hs.append(
        '        _ -> invalid "expected Geometry object"\n    checked (Right (Text text)) (`publish` out)\n'
    )
    hs.append(
        'foreign export ccall "hm_geometry_equal" equal :: StablePtr Value -> StablePtr Value -> Ptr (StablePtr Value) -> IO CInt\nequal :: StablePtr Value -> StablePtr Value -> Ptr (StablePtr Value) -> IO CInt\nequal first second out = boundary $ do\n    a <- deRefStablePtr first\n    b <- deRefStablePtr second\n    result <- case (valueInfo a,valueInfo b) of\n'
    )
    for typ, tag in TYPES.items():
        hs.append(
            "        (("
            + str(tag)
            + ",_,_),("
            + str(tag)
            + ",_,_)) -> (==) <$> (unwire a :: IO G."
            + typ
            + ") <*> unwire b\n"
        )
    hs.append(
        "        _ -> pure False\n    checked (Right (Boolean result)) (`publish` out)\n"
    )
    hs.append(
        'foreign export ccall "hm_geometry_parts" parts :: StablePtr Value -> Ptr (StablePtr Value) -> IO CInt\nparts :: StablePtr Value -> Ptr (StablePtr Value) -> IO CInt\nparts input out = boundary $ do\n    value <- deRefStablePtr input\n    result <- case valueInfo value of\n'
    )
    for typ, tag in TYPES.items():
        constructors = [
            e
            for e in data
            if e["name"][0].isupper() and e["signature"].split(" -> ")[-1] == typ
        ]
        if not constructors:
            continue
        hs.append(
            "        ("
            + str(tag)
            + ",_,_) -> do\n            object <- unwire value :: IO G."
            + typ
            + "\n            pure $ case object of\n"
        )
        for e in constructors:
            args = split_top(e["signature"], "->")[:-1]
            variables = ["field" + str(k) for k in range(len(args))]
            hs.append(
                "                G."
                + e["name"]
                + "".join(" " + v for v in variables)
                + " -> Tuple [Text "
                + json.dumps(e["name"])
                + ",Tuple ["
                + ",".join("wire " + v for v in variables)
                + "]]\n"
            )
    hs.append(
        '        _ -> unsupported "public constructor fields unavailable for this abstract Geometry type"\n    checked (Right result) (`publish` out)\n'
    )
    hs.append(
        'foreign export ccall "hm_geometry_apply" apply :: CInt -> Ptr (StablePtr Value) -> CSize -> Ptr (StablePtr Value) -> IO CInt\napply :: CInt -> Ptr (StablePtr Value) -> CSize -> Ptr (StablePtr Value) -> IO CInt\napply operation inputs arity out = boundary $ do\n    values <- peekArray (fromIntegral arity) inputs >>= mapM deRefStablePtr\n    case (operation,values) of\n'
    )
    py.append(
        '\n\ndef parts(value):\n    """Return the actual public constructor and typed fields."""\n    return _invoke("hmath_geometry_parts", [["GeometryObject"]], [value])\n\n\ndef describe(value):\n    """Return the original Show representation, never evaluated as code."""\n    return _invoke("hmath_geometry_describe", [["GeometryObject"]], [value])\n'
    )
    for op, e in enumerate(data):
        types = split_top(e["signature"], "->")
        args = types[:-1]
        result, checked = result_type(e["signature"])
        names = arguments(e)
        symbol = "hmath_geometry_" + public_name(e)
        declaration = (
            ["hmath_context *context"]
            + ["const hmath_value *" + n for n in names]
            + ["hmath_value **out"]
        )
        prototype = "hmath_status " + symbol + "(" + ", ".join(declaration) + ")"
        header.append(
            "/* "
            + e["module"]
            + "."
            + e["name"]
            + " :: "
            + e["signature"]
            + " */\nHMATH_API "
            + prototype
            + ";\n"
        )
        c.append(
            prototype
            + " {\n    if(!out"
            + "".join(" || !" + n for n in names)
            + ')return hm_error(HMATH_INVALID_ARGUMENT,"NULL Geometry argument");\n    hmath_value *temporary=NULL;\n    hmath_status status=hm_value_begin(context,&temporary);\n    if(status)return status;\n    void *arguments[]={'
            + (",".join("hm_value_stable(" + n + ")" for n in names) or "NULL")
            + "};\n    return hm_value_finish(temporary,hm_geometry_apply("
            + str(op)
            + ",arguments,"
            + str(len(args))
            + ",&temporary->stable),out);\n}\n"
        )
        hs.append(
            "        ("
            + str(op)
            + ",["
            + ",".join("v" + str(k) for k in range(len(args)))
            + "]) -> do\n"
        )
        for k, typ in enumerate(args):
            hs.append(
                "            arg"
                + str(k)
                + " <- "
                + (
                    "matrixInput v" + str(k)
                    if typ == "Matrix Double"
                    else "(unwire v" + str(k) + " :: IO (" + native_type(typ) + "))"
                )
                + "\n"
            )
        call = "G." + e["name"] + "".join(" arg" + str(k) for k in range(len(args)))
        encoder = (
            "matrixValue"
            if result == "Matrix Double"
            else "orderingValue"
            if result == "Ordering"
            else "nestedMaybeValue"
            if result in ("Maybe (Maybe Point3)", "Maybe (Maybe Line)")
            else "wire"
        )
        hs.append(
            "            checked ("
            + (call if checked else "Right (" + call + ")")
            + ") (\\result -> publish ("
            + encoder
            + " result) out)\n"
        )
        specs = [type_spec(t, KNOWN) for t in args]
        py.append(
            "\n\ndef "
            + public_name(e)
            + "("
            + ", ".join(names)
            + '):\n    """'
            + e["module"]
            + "."
            + e["name"]
            + " :: "
            + e["signature"]
            + '."""\n    result = _invoke('
            + repr(symbol)
            + ", "
            + repr(specs)
            + ", ["
            + ", ".join(names)
            + "])\n    return "
            + ("Ordering(result)" if result == "Ordering" else "result")
            + "\n"
        )
        docs.append(
            "## `"
            + public_name(e)
            + "`\n\n`geometry."
            + snake(e["name"])
            + "("
            + ", ".join(names)
            + ")`\n\n"
            + source_prose(e)
            + "\n\n```haskell\n"
            + e["signature"]
            + "\n```\n\n```c\n"
            + prototype
            + ";\n```\n\n"
        )
        mappings.append(
            {
                "symbol": e["module"] + "." + e["name"],
                "c": [symbol],
                "python": "hmath.geometry." + public_name(e),
                "specializations": ["original concrete types"],
            }
        )
        symbols.append(symbol)
        exports.append(public_name(e))
    hs.append('        _ -> invalid "Geometry operation identifier or arity differs"\n')
    header.append("#ifdef __cplusplus\n}\n#endif\n#endif\n")
    py.append(
        "\n\n__all__ = "
        + json.dumps(sorted(exports, key=lambda n: (not n.isupper(), n)), indent=4)
        + "\n"
    )
    return {
        "include/hmath_geometry.h": "".join(header),
        "cbits/geometry.c": "".join(c),
        "src/HMath/FFI/Geometry.hs": "".join(hs),
        "bindings/python/_hmath_native/geometry.py": "".join(py),
        "bindings/schema/geometry-objects.json": json.dumps(
            {"schema": 1, "bindings": mappings}, indent=2
        )
        + "\n",
        "bindings/schema/geometry-symbols.txt": "\n".join(symbols) + "\n",
        "docs/reference/geometry-bindings.md": "".join(docs),
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for name, content in generate().items():
        path = ROOT / name
        if args.check:
            if not path.exists() or path.read_text() != content:
                parser.exit(1, "Stale Geometry binding: " + name + "\n")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)


if __name__ == "__main__":
    main()
