ROOT = Path(__file__).resolve().parent.parent
OPS = json.loads((ROOT / "bindings/schema/polynomial-operations.json").read_text())


def snake(name):
    return re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", name).lower()


def source_doc(name):
    source = (ROOT / "src/HMath/Polynomial.hs").read_text()
    pos = source.find("\n" + name + " ::")
    before = source[:pos]
    line = before.rfind("\n-- |")
    block = before.rfind("\n{- |")
    start = max(line, block)
    text = before[start:].strip()
    if start == block:
        text = text.split("-}", 1)[0].replace("{- |", "", 1)
    else:
        text = text.replace("-- |", "", 1)
    return " ".join(text.replace("--", "").replace("@", "`").split())


