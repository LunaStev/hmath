def format_python(source):
    result = subprocess.run(
        [
            "ruff",
            "check",
            "--select",
            "I,RUF022",
            "--fix",
            "--stdin-filename",
            "polynomial.py",
            "-",
        ],
        input=source,
        text=True,
        capture_output=True,
        check=True,
    )
    return subprocess.run(
        ["ruff", "format", "--stdin-filename", "polynomial.py", "-"],
        input=result.stdout,
        text=True,
        capture_output=True,
        check=True,
    ).stdout


