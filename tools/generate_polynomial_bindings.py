            proto
            + " {\n if(!out || "
            + " || ".join("!" + a for a in args)
            + ') return hm_error(HMATH_INVALID_ARGUMENT,"NULL polynomial argument");\n hmath_value *result; hmath_status status=hm_value_begin(context,&result); if(status) return status;\n void *args[]={'
