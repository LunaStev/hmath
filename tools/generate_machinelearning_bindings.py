import argparse
import json
import re
from pathlib import Path

from generate_graph_bindings import snake, source_prose, split_top

ROOT = Path(__file__).resolve().parent.parent
SPECIAL = {
    "fitEncoder",
    "labelEncode",
    "labelDecode",
    "oneHotEncode",
    "stratifiedKFold",
}
PROTOTYPES = {"fitEncoder", "stratifiedKFold"}


def metadata():
    return json.loads(
        (ROOT / "bindings/schema/machinelearning-functions.json").read_text()
    )


def normalize(typ):
    typ = typ.strip()
    if "=>" in typ:
        typ = typ.split("=>", 1)[1].strip()
    return re.sub(r"\b(?:a|p)\b", "Value", typ)


def spec(typ):
    typ = normalize(typ)
    arrows = split_top(typ, "->")
    if len(arrows) > 1:
        return ["function", *[spec(x) for x in arrows]]
    if typ.startswith("Either MathError "):
        return ["either", spec(typ[17:])]
    if typ.startswith("Maybe "):
        inner = spec(typ[6:])
        if inner[0] == "maybe":
            raise ValueError("nested Maybe needs tagged transport")
        return ["maybe", inner]
    if typ == "Dataset":
        return ["list", ["list", ["Double"]]]
    if typ.startswith("["):
        return ["list", spec(typ[1:-1])]
    if typ.startswith("("):
        fields = split_top(typ[1:-1], ",")
        if len(fields) > 1:
            return ["tuple", *[spec(x) for x in fields]]
        return ["unit"] if not fields[0] else spec(fields[0])
    if typ.startswith("Fit "):
        return ["Fit"]
    if typ.startswith("Encoder "):
        return ["Encoder"]
    known = {e["name"] for e in metadata()["types"]} | {
        "Value",
        "Word64",
        "Double",
        "Int",
        "Bool",
    }
    if typ not in known:
        raise ValueError(typ)
    return [typ]


def native_type(typ):
    typ = normalize(typ)
    if typ.startswith("Either MathError "):
        return "(Either E.MathError " + native_type(typ[17:]) + ")"
    if typ.startswith("Maybe "):
        return "(Maybe " + native_type(typ[6:]) + ")"
    if typ.startswith("["):
        return "[" + native_type(typ[1:-1]) + "]"
    if typ.startswith("("):
        inner = typ[1:-1]
        arrows = split_top(inner, "->")
        return (
            "(" + " -> ".join(native_type(x) for x in arrows) + ")"
            if len(arrows) > 1
            else "(" + ",".join(native_type(x) for x in split_top(inner, ",")) + ")"
        )
    if typ == "Value":
        return "V.Value"
    if typ.startswith("Fit "):
        return "(M.Fit " + native_type(typ[4:]) + ")"
    if typ.startswith("Encoder "):
        return "(M.Encoder " + native_type(typ[8:]) + ")"
    return "M." + typ if typ in {e["name"] for e in metadata()["types"]} else typ


def names(entry):
    types = split_top(normalize(entry["signature"]), "->")[:-1]
    result = []
    for typ in types:
        base = (
            "function"
            if "->" in typ
            else "dataset"
            if typ == "Dataset"
            else "values"
            if typ.startswith("[")
            else {
                "Double": "number",
                "Int": "count",
                "Bool": "flag",
                "Word64": "seed",
                "a": "value",
                "p": "value",
                "Value": "value",
            }.get(typ, snake(typ.split()[0]))
        )
        if base in {"class", "operator", "template", "union"}:
            base += "Value"
        name = base
        index = 2
        while name in result:
            name = base + str(index)
            index += 1
        result.append(name)
    return result


def generate():
    data = metadata()
    entries = data["functions"]
    types = {
        e["name"]: (310 + k, e["module"])
        for k, e in enumerate(e for e in data["types"] if e["name"] != "Dataset")
    }
    assert types["Fit"][0] == 321 and types["Encoder"][0] == 329
    base = [
        "{-# LANGUAGE FlexibleInstances #-}\n{-# OPTIONS_GHC -Wno-orphans #-}\n-- SPDX-License-Identifier: MPL-2.0\n-- Generated by tools/generate_machinelearning_bindings.py.\nmodule HMath.FFI.MachineLearning.Types where\nimport HMath.FFI.NumericalCodec (From(..),To(..),box,unbox)\nimport qualified HMath.MachineLearning as M\n"
    ]
    for typ, (tag, _) in types.items():
        if typ in ("Fit", "Encoder"):
            continue
        getters = [
            e["name"]
            for e in entries
            if e["signature"].startswith(typ + " -> ")
            and len(split_top(e["signature"], "->")) == 2
            and not e["signature"].split("->")[-1].strip().startswith("Either ")
        ]
        base.append(
            "instance From M."
            + typ
            + " where from = unbox "
            + str(tag)
            + "\ninstance To M."
            + typ
            + " where to value = pure (box "
            + str(tag)
            + " value ["
            + ",".join("to (M." + g + " value)" for g in getters)
            + "])\n"
        )
    hs = [
        "{-# LANGUAGE ForeignFunctionInterface #-}\n-- SPDX-License-Identifier: MPL-2.0\n-- Generated by tools/generate_machinelearning_bindings.py.\nmodule HMath.FFI.MachineLearning where\nimport Foreign\nimport Foreign.C\nimport qualified HMath.Error as E\nimport qualified HMath.FFI.Boundary as B\nimport qualified HMath.FFI.NumericalCodec as N\nimport qualified HMath.FFI.Value as V\nimport qualified HMath.FFI.MachineLearning.Codec as C\nimport HMath.FFI.MachineLearning.Types ()\nimport qualified HMath.MachineLearning as M\n"
    ]
    header = [
        '/* SPDX-License-Identifier: MPL-2.0 */\n/* Generated by tools/generate_machinelearning_bindings.py. */\n#ifndef HMATH_MACHINELEARNING_H\n#define HMATH_MACHINELEARNING_H\n#include "hmath_linear.h"\n#ifdef __cplusplus\nextern "C" {\n#endif\n',
        "/* Original immutable models/configurations; Dataset is a list of Double rows.\n * Inputs are borrowed; each successful output transfers one owned Value. Error\n * outputs remain untouched; release with hmath_value_release. Source fitting\n * methods, seeds, data limits, validation, tie order, convergence diagnostics\n * and MathError/status11 are unchanged. Calls may share immutable inputs with\n * independent references/output addresses. Live owners pin the runtime.\n * Search callbacks use kind101 checked callbacks with tuple(config,Fold) and\n * Double results; retain function/userdata while referenced. Python preserves\n * callback owners and rethrows unexpected exceptions after native cleanup.\n * Encoder/stratified labels use actual native Ord/Eq dictionaries, with no\n * Double/text conversion. Optional prototype is a representative category\n * solely for otherwise uninferrable empty/optional element types. */\n",
    ]
    c = [
        '/* SPDX-License-Identifier: MPL-2.0 */\n/* Generated by tools/generate_machinelearning_bindings.py. */\n#include "hmath_machinelearning.h"\n#include "value_internal.h"\nextern int hm_ml_apply(int,void *const *,size_t,void *,void **);\n'
    ]
    py = [
        '# SPDX-License-Identifier: MPL-2.0\n# Generated by tools/generate_machinelearning_bindings.py; do not edit.\n"""Original immutable estimators, preprocessing, labels and fit diagnostics."""\nfrom ._numerical_base import _invoke\nfrom ._value import Value, register\n\nDataset = list\n'
    ]
    mappings = []
    symbols = []
    exports = ["Dataset", "parts", "describe"]
    source_names = {e["module"] + "." + e["name"] for e in entries}
    docs = [
        "# Machine-learning bindings\n\n`from hmath import machinelearning` exposes the original dense CPU estimators. `Dataset` is a list of finite Double observation rows. No estimator, preprocessing rule, seed, stopping rule, feature ordering or class tie order is substituted. Fit preprocessing inside each training fold; successful fitting preserves the source residual, completed iterations and convergence flag rather than implying an optimum was reached.\n\nC includes `hmath_machinelearning.h`; values follow the [owned structured protocol](values.md). All inputs are borrowed for a synchronous call; outputs transfer one reference and stay untouched on failure. Original MathError/status11 retains full constructor/payload. Immutable owners support independent readers holding their own references; final shutdown is BUSY while owners exist. Python supports close()/context managers.\n\n`fitted(result)` returns an independently owned model/payload. `fit_iterations`, `fit_residual`, and `fit_converged` preserve the original diagnostics. Generic Fit payloads retain their structure and native precision. Search callbacks receive `(configuration, Fold)` as two positional arguments and return a Double loss; original mathematical failures remain checked Left errors, while unexpected Python exceptions rethrow after native cleanup. Retained callback owners travel with returned objects.\n\nCategorical encoders retain actual native Ord/Eq dictionaries, including exact integers/rationals, typed FP32/64, bounded integers, Bool/String, recursive collection labels and supported native domain types. No labels become Double approximations or text keys. Explicit `prototype=` is required when collection/optional element types cannot be inferred; it is a type example, never a training label. Empty input failures retain the original source error. Existing encoders retain their learned native label type for every subsequent operation.\n\n"
    ]
    for typ, (tag, module) in types.items():
        py.append(
            "\n\nclass "
            + typ
            + '(Value):\n    """Actual immutable '
            + module
            + "."
            + typ
            + ' owner."""\n\n\nregister('
            + str(tag)
            + ", "
            + typ
            + ")\n"
        )
        header.append(
            "typedef hmath_value hmath_ml_"
            + snake(typ)
            + "_object; /* kind"
            + str(tag)
            + " */\n"
        )
        exports.append(typ)
        if module + "." + typ not in source_names:
            mappings.append(
                {
                    "symbol": module + "." + typ,
                    "c": ["hmath_ml_" + snake(typ) + "_object"],
                    "python": "hmath.machinelearning." + typ,
                    "specializations": [
                        "actual native supported category dictionaries"
                        if typ == "Encoder"
                        else "original concrete types"
                    ],
                }
            )
    header.append(
        "typedef hmath_value hmath_ml_dataset_value; /* list of Double rows */\n"
    )
    mappings.append(
        {
            "symbol": "HMath.MachineLearning.Internal.Dataset",
            "c": ["hmath_ml_dataset_value"],
            "python": "hmath.machinelearning.Dataset",
            "specializations": ["original Double rows"],
        }
    )
    for helper in ("describe", "parts"):
        prototype = (
            "hmath_status hmath_ml_"
            + helper
            + "(hmath_context *context,const hmath_value *value,hmath_value **out)"
        )
        header.append("HMATH_API " + prototype + ";\n")
        c.append(
            "extern int hm_ml_"
            + helper
            + "(void *,void **);\n"
            + prototype
            + ' {\n    if(!value||!out)return hm_error(HMATH_INVALID_ARGUMENT,"NULL ML helper argument");\n    hmath_value *result=NULL;\n    hmath_status status=hm_value_begin(context,&result);\n    if(status)return status;\n    return hm_value_finish(result,hm_ml_'
            + helper
            + "(hm_value_stable(value),&result->stable),out);\n}\n"
        )
        symbols.append("hmath_ml_" + helper)
        py.append(
            "\n\ndef "
            + helper
            + '(value):\n    """Inspect original native state without evaluating text as mathematics."""\n    return _invoke("hmath_ml_'
            + helper
            + '", [["Value"]], [value])\n'
        )
    hs.append(
        'foreign export ccall "hm_ml_describe" describe :: StablePtr V.Value -> Ptr (StablePtr V.Value) -> IO CInt\ndescribe :: StablePtr V.Value -> Ptr (StablePtr V.Value) -> IO CInt\ndescribe input out = B.boundary $ do\n    value <- deRefStablePtr input\n    text <- case V.valueInfo value of\n'
    )
    for typ, (tag, _) in types.items():
        if typ in ("Fit", "Encoder"):
            continue
        hs.append(
            "        ("
            + str(tag)
            + ",_,_) -> show <$> (N.from value :: IO M."
            + typ
            + ")\n"
        )
    hs.append(
        '        _ -> V.unsupported "use original Fit/Encoder getters for generic payloads"\n    B.checked (Right (V.Text text)) (`V.publish` out)\n'
    )
    hs.append(
        'foreign export ccall "hm_ml_parts" parts :: StablePtr V.Value -> Ptr (StablePtr V.Value) -> IO CInt\nparts :: StablePtr V.Value -> Ptr (StablePtr V.Value) -> IO CInt\nparts input out = B.boundary $ do\n    value <- deRefStablePtr input\n    result <- case V.valueInfo value of\n'
    )
    for typ, (tag, _) in types.items():
        ctors = [
            e
            for e in entries
            if e["name"][0].isupper()
            and split_top(e["signature"], "->")[-1] in (typ, typ + " a")
        ]
        if not ctors:
            continue
        hs.append(
            "        ("
            + str(tag)
            + ",_,_) -> do\n            original <- N.from value :: IO "
            + ("(M.Fit V.Value)" if typ == "Fit" else "M." + typ)
            + "\n            case original of\n"
        )
        for e in ctors:
            fields = [
                "field" + str(k)
                for k in range(len(split_top(e["signature"], "->")) - 1)
            ]
            hs.append(
                "                M."
                + e["name"]
                + "".join(" " + f for f in fields)
                + " -> do\n                    fields <- sequence ["
                + ",".join("N.to " + f for f in fields)
                + "]\n                    pure (V.Tuple [V.Text "
                + json.dumps(e["name"])
                + ",V.Tuple fields])\n"
            )
    hs.append(
        '        _ -> V.unsupported "original model type has no public constructor"\n    B.checked (Right result) (`V.publish` out)\n'
    )
    hs.append(
        'foreign export ccall "hm_ml_apply" apply :: CInt -> Ptr (StablePtr V.Value) -> CSize -> StablePtr V.Value -> Ptr (StablePtr V.Value) -> IO CInt\napply :: CInt -> Ptr (StablePtr V.Value) -> CSize -> StablePtr V.Value -> Ptr (StablePtr V.Value) -> IO CInt\napply operation inputs arity prototypePointer out = B.boundary $ do\n    values <- peekArray (fromIntegral arity) inputs >>= mapM deRefStablePtr\n    prototype <- if castStablePtrToPtr prototypePointer == nullPtr then pure V.None else deRefStablePtr prototypePointer\n    result <- case operation of\n'
    )
    for op, e in enumerate(entries):
        source = e["module"] + "." + e["name"]
        signature = normalize(e["signature"])
        pieces = split_top(signature, "->")
        arguments = pieces[:-1]
        args = names(e)
        symbol = "hmath_ml_" + snake(e["name"])
        proto = e["name"] in PROTOTYPES
        prototype = (
            "hmath_status "
            + symbol
            + "("
            + ", ".join(
                ["hmath_context *context"]
                + ["const hmath_value *" + a for a in args]
                + (["const hmath_value *prototype"] if proto else [])
                + ["hmath_value **out"]
            )
            + ")"
        )
        header.append(
            "/* "
            + source
            + " :: "
            + e["signature"]
            + " */\nHMATH_API "
            + prototype
            + ";\n"
        )
        c.append(
            prototype
            + " {\n    if(!out"
            + "".join(" || !" + a for a in args)
            + ')return hm_error(HMATH_INVALID_ARGUMENT,"NULL ML argument");\n    hmath_value *result=NULL;\n    hmath_status status=hm_value_begin(context,&result);\n    if(status)return status;\n    void *arguments[]={'
            + (",".join("hm_value_stable(" + a + ")" for a in args) or "NULL")
            + "};\n    return hm_value_finish(result,hm_ml_apply("
            + str(op)
            + ",arguments,"
            + str(len(args))
            + ","
            + ("prototype?hm_value_stable(prototype):NULL" if proto else "NULL")
            + ",&result->stable),out);\n}\n"
        )
        if e["name"] in SPECIAL:
            variables = ["v" + str(k) for k in range(len(args))]
            hs.append(
                "        "
                + str(op)
                + " -> case values of\n            ["
                + ",".join(variables)
                + "] -> C."
                + e["name"]
                + "".join(" " + v for v in variables)
                + (" prototype" if proto else "")
                + '\n            _ -> V.invalid "category operation arity differs"\n'
            )
        else:
            native = " -> ".join(native_type(x) for x in pieces)
            hs.append(
                "        "
                + str(op)
                + " -> N.apply (M."
                + e["name"]
                + " :: "
                + native
                + ") values\n"
            )
        specs = [spec(a) for a in arguments]
        publicargs = args + (["*", "prototype=None"] if proto else [])
        py.append(
            "\n\ndef "
            + snake(e["name"])
            + "("
            + ", ".join(publicargs)
            + '):\n    """'
            + source
            + " :: "
            + e["signature"]
            + '."""\n    return _invoke('
            + repr(symbol)
            + ", "
            + repr(specs + ([["Value"]] if proto else []))
            + ", ["
            + ", ".join(args + (["prototype"] if proto else []))
            + "])\n"
        )
        docs.append(
            "## `"
            + snake(e["name"])
            + "`\n\n`machinelearning."
            + snake(e["name"])
            + "("
            + ", ".join(publicargs)
            + ")`\n\n"
            + source_prose(e)
            + "\n\n```haskell\n"
            + e["signature"]
            + "\n```\n\n```c\n"
            + prototype
            + ";\n```\n\n"
        )
        mappings.append(
            {
                "symbol": source,
                "c": [symbol],
                "python": "hmath.machinelearning." + snake(e["name"]),
                "specializations": [
                    "actual native supported Ord/Eq dictionary; no arbitrary user-defined instance claim"
                    if e["name"] in SPECIAL
                    else "generic record/configuration payload preserved"
                    if any(v in e["signature"] for v in ("Fit a", "[p]", " p "))
                    else "original concrete types"
                ],
            }
        )
        symbols.append(symbol)
        exports.append(snake(e["name"]))
    hs.append(
        '        _ -> V.invalid "ML operation identifier differs"\n    B.checked (Right result) (`V.publish` out)\n'
    )
    py.append(
        "\n\n__all__ = "
        + json.dumps(sorted(exports, key=lambda n: (not n.isupper(), n)), indent=4)
        + "\n"
    )
    header.append("#ifdef __cplusplus\n}\n#endif\n#endif\n")
    return {
        "include/hmath_machinelearning.h": "".join(header),
        "cbits/machinelearning.c": "".join(c),
        "src/HMath/FFI/MachineLearning.hs": "".join(hs),
        "src/HMath/FFI/MachineLearning/Types.hs": "".join(base),
        "bindings/python/_hmath_native/machinelearning.py": "".join(py),
        "bindings/schema/machinelearning-objects.json": json.dumps(
            {"schema": 1, "bindings": mappings}, indent=2
        )
        + "\n",
        "bindings/schema/machinelearning-symbols.txt": "\n".join(symbols) + "\n",
        "docs/reference/machinelearning-bindings.md": "".join(docs),
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for name, content in generate().items():
        path = ROOT / name
        if args.check:
            if not path.exists() or path.read_text() != content:
                parser.exit(1, "Stale ML bindings: " + name + "\n")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)


if __name__ == "__main__":
    main()
