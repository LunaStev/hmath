near :: Double -> Double -> Bool
near x y = abs (x - y) <= 1e-7 * max 1 (max (abs x) (abs y))
vec :: [Double] -> [Double] -> Bool
vec a b = length a == length b && and (zipWith near a b)
ok :: Either a Bool -> Bool
ok = either (const False) id
isLeft :: Either a b -> Bool
isLeft (Left _) = True
isLeft _ = False
equals :: (Eq b) => Either a b -> b -> Bool
equals x y = either (const False) (== y) x
values :: Either a I.Image -> [Double] -> Bool
values result expected = either (const False) (\img -> vec (I.imageValues img) expected) result
signal :: [Double]
signal =
    [ sin (0.63 * fromIntegral i) + 0.3 * cos (0.17 * fromIntegral i) + 0.01 * fromIntegral i
    | i <- [0 :: Int .. 79]
    ]
options :: O.OptimizeOptions
options = O.OptimizeOptions 1000 5000 1e-6 0.01

applicationBatchTests :: [(String, Bool)]
applicationBatchTests = timeTests ++ forecastTests ++ imageTests ++ parametricTests

timeTests :: [(String, Bool)]
timeTests =
    [
        ( "series regular missing conversion"
        , ok
            ( do
                s <- T.regularSeries 10 0.5 [Just 1, Nothing, Just 3]
                r <- T.isRegular 1e-10 s
                Right (r && isLeft (T.seriesValues s))
            )
        )
    ,
        ( "series duplicate/NaN rejection"
        , isLeft (T.series [(0, Just 1), (0, Just 2)]) && isLeft (T.series [(0, Just (0 / 0))])
        )
    , ("series timestamp representability", isLeft (T.regularSeries 1e300 1 [Just 0, Just 1]))
    ,
        ( "series irregular detection"
        , ok (T.series [(0, Just 1), (1, Just 2), (3, Just 3)] >>= T.isRegular 1e-10 >>= Right . not)
        )
    ,
        ( "series exact alignment"
        , ok
            ( do
                a <- T.series [(0, Just 1), (2, Just 2)]
                b <- T.series [(1, Just 3), (2, Just 4)]
                (x, y) <- T.align T.Outer a b
                Right
                    ( T.observations x == [(0, Just 1), (1, Nothing), (2, Just 2)]
                        && T.observations y == [(0, Nothing), (1, Just 3), (2, Just 4)]
                    )
            )
        )
    ,
        ( "series directional fills"
        , ok
            ( do
                s <- T.regularSeries 0 1 [Nothing, Just 2, Nothing, Just 4, Nothing]
                a <- T.fillMissing T.ForwardFill s
                b <- T.fillMissing T.BackwardFill s
                Right
                    ( map snd (T.observations a) == [Nothing, Just 2, Just 2, Just 4, Just 4]
                        && map snd (T.observations b) == [Just 2, Just 2, Just 4, Just 4, Nothing]
                    )
            )
        )
    ,
        ( "series irregular linear fill"
        , ok
            ( do
                s <- T.series [(0, Just 2), (1, Nothing), (4, Just 10), (6, Nothing)]
                y <- T.fillMissing T.LinearFill s
                Right (map snd (T.observations y) == [Just 2, Just 4, Just 10, Nothing])
            )
        )
    ,
        ( "series extreme timestamp interpolation"
        , ok
            ( do
                s <- T.series [(-1e308, Just 0), (0, Nothing), (1e308, Just 1)]
                a <- T.fillMissing T.LinearFill s
                b <- T.resample T.LinearSamples 0 1 1 s
                Right
                    (map snd (T.observations a) == [Just 0, Just 0.5, Just 1] && map snd (T.observations b) == [Nothing])
            )
        )
    ,
        ( "series resampling linear no extrapolation"
        , ok
            ( do
                s <- T.series [(0, Just 2), (2, Just 6)]
                y <- T.resample T.LinearSamples (-1) 1 5 s
                Right (map snd (T.observations y) == [Nothing, Just 2, Just 4, Just 6, Nothing])
            )
        )
    ,
        ( "series resampling half-open bins"
        , ok
            ( do
                s <- T.regularSeries 0 1 (map Just [1, 3, 5, 7, 9])
                a <- T.resample T.BinMean 0 2 2 s
                b <- T.resample T.BinLast 0 2 2 s
                av <- T.seriesValues a
                bv <- T.seriesValues b
                Right (vec av [2, 6] && vec bv [3, 7])
            )
        )
    ,
        ( "series rolling mean/variance/sd/min/max"
        , and
            [ equals (T.rolling method 2 [1, 3, 5]) expected
            | (method, expected) <-
                [ (T.MovingMean, [2, 4])
                , (T.MovingVariance, [1, 1])
                , (T.MovingSD, [1, 1])
                , (T.MovingMinimum, [1, 3])
                , (T.MovingMaximum, [3, 5])
                ]
            ]
        )
    ,
        ( "series EMA and chronological weights"
        , equals (T.exponentialAverage 0.5 [1, 3, 5]) [1, 2, 3.5]
            && equals (T.weightedAverage [1, 3] [1, 3, 5]) [2.5, 4.5]
        )
    ,
        ( "series positive price returns"
        , ok
            ( do
                a <- T.cumulativeReturns [2, 4, 8]
                b <- T.logarithmicReturns [2, 4, 8]
                Right (vec a [0, 1, 3] && vec b (replicate 2 (log 2)))
            )
            && isLeft (T.logarithmicReturns [0, 1])
        )
    ,
        ( "series ordinary/seasonal differences"
        , equals (T.difference 2 1 [0, 1, 4, 9, 16]) [2, 2, 2]
            && equals (T.difference 1 2 [1, 3, 6, 10]) [5, 7]
        )
    ,
        ( "series ACF/PACF Toeplitz reference"
        , ok
            ( do
                (b, _, _) <- T.yuleWalker 3 signal
                acf <- T.autocorrelation 3 signal
                pacf <- T.partialAutocorrelation 3 signal
                Right
                    ( vec b [2.0233623239257383, -1.6293621221211294, 0.4247322682829465]
                        && near (acf !! 0) 1
                        && near (pacf !! 0) 1
                        && near (pacf !! 3) (b !! 2)
                    )
            )
        )
    ,
        ( "series Levinson analytic AR1 covariance"
        , ok
            ( do
                (b, v, p) <- T.durbinLevinson [2, 1, 0.5, 0.25]
                Right (vec b [0.5, 0, 0] && near v 1.5 && vec p [0.5, 0, 0])
            )
        )
    ,
        ( "series cross-correlation lag convention"
        , ok
            ( do
                a <- T.crossCorrelation 1 [1, 0, -1, 0] [0, 1, 0, -1]
                b <- T.crossCorrelation (-1) [0, 1, 0, -1] [1, 0, -1, 0]
                Right (near a 1 && near b 1)
            )
        )
    ,
        ( "series ADF independent OLS golden"
        , ok
            ( do
                r <- T.augmentedDickeyFuller T.Level 2 signal
                Right (near (T.stationarityStatistic r) 1.3993631478673514 && T.stationarityObservations r == 77)
            )
        )
    ,
        ( "series KPSS independent Bartlett golden"
        , ok (do r <- T.kpss T.Level 3 signal; Right (near (T.stationarityStatistic r) 0.2346264042967811))
        )
    ,
        ( "series stationarity degeneracy"
        , isLeft (T.augmentedDickeyFuller T.Level 0 (replicate 20 1))
            && isLeft (T.kpss T.Level 0 (replicate 20 1))
        )
    ,
        ( "series exact change point segmentation"
        , equals (T.changePoints 0.5 2 [0, 0, 0, 5, 5, 5, -2, -2, -2]) [3, 6]
            && equals (T.changePoints 1e6 1 [0, 0, 5, 5]) []
        )
    ,
        ( "series overflow rejected before change-point minima"
        , isLeft (T.changePoints 1 1 [1e200, -1e200, 1e200, -1e200])
        )
    ,
        ( "series huge MAD scale avoids false normality"
        , equals (T.anomalies 0.1 [-1.6e308, -1.5e308, 1.5e308, 1.6e308]) [0, 1, 2, 3]
        )
    ,
        ( "series CUSUM and robust anomalies"
        , equals (T.cusum 0 1 0.5 3 [0, 0, 3, 3]) [3] && equals (T.anomalies 3 [1, 1, 1, 10]) [3]
        )
    , ("series CUSUM cancelling large drift", equals (T.cusum 0 1 1e308 1.5e308 [1.7e308, 1.7e308]) [])
    , ("series CUSUM overflow before threshold reset", isLeft (T.cusum 0 1 0 1.5e308 [1e308, 1e308]))
    ,
        ( "series DTW identity and band constraints"
        , ok
            ( do
                r <- T.dynamicTimeWarping 0 [1, 2, 3] [1, 2, 3]
                Right (T.dtwDistance r == 0 && T.dtwPath r == [(0, 0), (1, 1), (2, 2)])
            )
            && isLeft (T.dynamicTimeWarping 0 [1] [1, 2])
        )
    ,
        ( "series DTW nontrivial path"
        , ok
            ( do
                r <- T.dynamicTimeWarping 2 [1, 2, 3] [1, 1, 2, 3]
                Right (T.dtwDistance r == 0 && length (T.dtwPath r) == 4)
            )
        )
    ,
        ( "series spectrum Parseval and sine peak"
        , ok
            ( do
                bins <- T.spectrum 16 [sin (2 * pi * 3 * fromIntegral k / 16) | k <- [0 :: Int .. 15]]
                Right (near (sum (map snd bins)) 0.5 && near (snd (bins !! 3)) 0.5)
            )
        )
    ,
        ( "series forecast metrics"
        , and
            [ ok ((`near` answer) <$> T.forecastError metric [1, 2, 3] [2, 2, 2])
            | (metric, answer) <-
                [ (T.MAE, 2 / 3)
                , (T.MSE, 2 / 3)
                , (T.RMSE, sqrt (2 / 3))
                , (T.MAPE, 400 / 9)
                , (T.SMAPE, 320 / 9)
                , (T.MASE 1 [1, 2, 3, 4], 2 / 3)
                ]
            ]
        )
    ,
        ( "series metric degenerate ranges"
        , isLeft (T.forecastError T.MAPE [0] [1])
            && isLeft (T.forecastError (T.MASE 1 [1, 1]) [1] [2])
            && equals (T.forecastError T.SMAPE [0] [0]) 0
        )
    ,
        ( "series bounded/invalid numerical inputs"
        , isLeft (T.rolling T.MovingMean 0 [1])
            && isLeft (T.weightedAverage [0] [1])
            && isLeft (T.difference 1 maxBound [1, 2])
            && isLeft (T.autocorrelation maxBound [1, 2])
            && isLeft (T.durbinLevinson [1, 2])
            && isLeft (T.series (replicate 16385 (0, Just 1)))
        )
    ]

forecastTests :: [(String, Bool)]
forecastTests =
    [
        ( "forecast simple smoothing hand recurrence"
        , ok
            ( do
                (f, y) <- T.smoothForecast (T.Simple 0.5) 2 [1, 3, 5]; Right (vec f [1, 1, 2] && vec y [3.5, 3.5])
            )
        )
    ,
        ( "forecast Holt exact ramp"
        , ok (do (_, y) <- T.smoothForecast (T.Holt 0.3 0.2) 3 [1 .. 20]; Right (vec y [21, 22, 23]))
        )
    ,
        ( "forecast additive Holt-Winters seasonal series"
        , ok
            ( do
                (_, y) <- T.smoothForecast (T.HoltWinters 4 0.5 0.1 0.4) 4 (concat (replicate 6 [1, 3, 2, 4]))
                Right (vec y [1, 3, 2, 4])
            )
        )
    , ("forecast decomposition exact reconstruction", reconstruct (T.decompose 4 seasonalSignal))
    ,
        ( "forecast STL linear seasonal recovery"
        , ok
            ( do
                d <- T.stl (T.defaultSTLConfig 4) seasonalSignal
                Right
                    ( maximum (map abs (T.remainderComponent d)) < 1e-5
                        && vec
                            (zipWith3 (\a b c -> a + b + c) (T.trendComponent d) (T.seasonalComponent d) (T.remainderComponent d))
                            seasonalSignal
                    )
            )
        )
    ,
        ( "forecast robust STL finite reconstruction"
        , reconstruct (T.stl ((T.defaultSTLConfig 4){T.stlRobustIterations = 2}) seasonalSignal)
        )
    ,
        ( "forecast AR exact affine recurrence"
        , ok
            ( do
                m <- T.fitAR 1 (take 30 (iterate (\x -> 1 + 0.7 * x) 0))
                y <- T.forecastAR 3 m
                Right
                    (vec (T.arCoefficients m) [1, 0.7] && vec y (take 3 (drop 30 (iterate (\x -> 1 + 0.7 * x) 0))))
            )
        )
    ,
        ( "forecast AR0 sample mean"
        , ok (do m <- T.fitAR 0 [1, 2, 4, 5]; y <- T.forecastAR 2 m; Right (vec y [3, 3]))
        )
    ,
        ( "forecast ARIMA drift integration"
        , ok
            ( do
                m <- T.fitARIMA options 0 1 0 [1, 3 .. 41]
                y <- T.forecastARIMA 3 m
                Right (vec y [43, 45, 47] && near (T.arimaInnovationVariance m) 0)
            )
        )
    ,
        ( "forecast SARIMA seasonal integration"
        , ok
            ( do
                m <- T.fitSARIMA options (T.SARIMAOrder 0 0 0 0 1 0 4) (concat (replicate 5 [1, 3, 2, 4]))
                y <- T.forecastARIMA 4 m
                Right (vec y [1, 3, 2, 4])
            )
        )
    ,
        ( "forecast MA conditional fit"
        , ok
            ( do
                m <- T.fitMA options 1 maSignal
                Right
                    ( length (T.arimaResiduals m) == 128
                        && near (T.arimaInnovationVariance m) 0.340940177387318
                        && and
                            (zipWith (\a b -> abs (a - b) < 1e-4) (T.arimaParameters m) [0.22369376698093366, 0.5354365113239544])
                    )
            )
        )
    ,
        ( "forecast ARMA conditional fit"
        , ok
            ( do
                m <- T.fitARMA options 1 1 armaSignal
                Right
                    ( length (T.arimaResiduals m) == 128
                        && near (T.arimaInnovationVariance m) 0.33977929075496754
                        && and
                            ( zipWith
                                (\a b -> abs (a - b) < 1e-4)
                                (T.arimaParameters m)
                                [0.2545852378134167, 0.5435089524946368, 0.5634656408339305]
                            )
                    )
            )
        )
    ,
        ( "forecast multiplicative SARIMA cross lags"
        , ok
            ( do
                m <- T.fitSARIMA options (T.SARIMAOrder 1 0 0 1 0 0 4) (take 50 signal)
                y <- T.forecastARIMA 3 m
                Right (length (T.arimaParameters m) == 3 && length y == 3)
            )
        )
    ,
        ( "forecast fit budgets and invalid shape"
        , isLeft (T.fitMA options{O.optMaxEvaluations = 1} 1 signal)
            && isLeft (T.fitAR 4 [1, 2])
            && isLeft (T.smoothForecast (T.Holt 2 0) 1 [1, 2])
            && isLeft (T.stl (T.defaultSTLConfig 0) signal)
        )
    ,
        ( "forecast VAR independent OLS prediction"
        , ok
            ( do
                let xs =
                        [ [sin (0.71 * fromIntegral i) + 0.1 * cos (0.13 * fromIntegral i), cos (0.39 * fromIntegral i)]
                        | i <- [0 :: Int .. 29]
                        ]
                model <- T.fitVAR 1 xs
                forecast <- T.forecastVAR 1 model
                design <- M.fromListChecked 29 3 (concat [1 : row | row <- take 29 xs])
                b1 <- QR.leastSquares design [row !! 0 | row <- drop 1 xs]
                b2 <- QR.leastSquares design [row !! 1 | row <- drop 1 xs]
                Right (vec (forecast !! 0) [sum (zipWith (*) b (1 : last xs)) | b <- [b1, b2]])
            )
        )
    ,
        ( "forecast Kalman series Joseph-form reuse"
        , ok
            ( do
                initial <- S.gaussianState [0] [[1]]
                states <- T.kalmanSeries [[1]] [[1]] [[0]] [[1]] initial [[2], [2]]
                Right (vec (S.stateMean (states !! 0)) [1] && vec (S.stateMean (states !! 1)) [4 / 3])
            )
        )
    ]
  where
    noise =
        take
            128
            [ fromInteger state / 2147483648 - 1
            | state <-
                drop 1 (iterate (\state -> (1664525 * state + 1013904223) `mod` 4294967296) (42 :: Integer))
            ]
    maSignal = zipWith (\e old -> 0.2 + e + 0.4 * old) noise (0 : noise)
    armaSignal = build 0 0 noise
      where
        build _ _ [] = []
        build previous old (e : es) = let value = 0.2 + 0.6 * previous + e + 0.4 * old in value : build value e es
    seasonalSignal = [0.1 * fromIntegral i + [1, 3, 2, 4] !! (i `mod` 4) | i <- [0 :: Int .. 47]]
    reconstruct result =
        ok
            ( do
                d <- result
                Right
                    ( vec
                        (zipWith3 (\a b c -> a + b + c) (T.trendComponent d) (T.seasonalComponent d) (T.remainderComponent d))
                        seasonalSignal
                    )
            )

imageTests :: [(String, Bool)]
imageTests =
    [
        ( "image constructor invalid shapes/nonfinite"
        , isLeft (I.image [] 1 [1])
            && isLeft (I.image [0, 2] 1 [])
            && isLeft (I.image [maxBound, 2] 1 [])
            && isLeft (I.image [1] 1 [0 / 0])
        )
    ,
        ( "image ND tensor/channel roundtrip"
        , ok
            ( do
                a <- I.image [2, 1, 2] 2 [0 .. 7]
                t <- I.toTensor a
                b <- I.fromTensor t
                r <- I.channel 0 a
                g <- I.channel 1 a
                c <- I.combineChannels [r, g]
                Right (a == b && a == c && isLeft (I.pixel a [2, 0, 0]))
            )
        )
    ,
        ( "image normalization/brightness/contrast/gamma"
        , ok
            ( do
                a <- I.image [3] 1 [1, 2, 3]
                b <- I.normalize 0 1 a
                c <- I.brightness 1 b >>= I.contrast 2 1
                d <- I.gamma 2 c
                Right (vec (I.imageValues d) [1, 4, 9])
            )
        )
    ,
        ( "image huge-range normalization"
        , ok
            ( do
                a <- I.image [3] 1 [-1e308, 0, 1e308]
                b <- I.normalize 0 1 a
                Right (vec (I.imageValues b) [0, 0.5, 1])
            )
        )
    ,
        ( "image transfer function thresholds"
        , ok
            ( do
                a <- I.srgbToLinear 0.04045
                b <- I.linearToSrgb 0.0031308
                Right (near a (0.04045 / 12.92) && near b (12.92 * 0.0031308))
            )
        )
    ,
        ( "image encoded overflow checked before hue conversion"
        , isLeft (I.image [1] 3 [-1e308, 0, 0] >>= I.convertColor I.LinearRGB I.HSV)
        )
    ,
        ( "image primary HSV/HSL and YCbCr"
        , ok
            ( do
                a <- I.image [1] 3 [1, 0, 0]
                hsv <- I.convertColor I.SRGB I.HSV a
                hsl <- I.convertColor I.SRGB I.HSL a
                ycc <- I.convertColor I.SRGB I.YCbCr a
