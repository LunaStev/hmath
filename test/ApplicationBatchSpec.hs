parametricTests :: [(String, Bool)]
parametricTests =
    [ ( "image color roundtrip " ++ show space ++ " " ++ show rgb
      , ok
            ( do
                a <- I.image [1] 3 rgb
                b <- I.convertColor I.SRGB space a
                c <- I.convertColor space I.SRGB b
                Right (and (zipWith (\x y -> abs (x - y) < 2e-5) rgb (I.imageValues c)))
            )
      )
    | space <- [I.LinearRGB, I.HSV, I.HSL, I.XYZ, I.Lab, I.YCbCr]
    , rgb <- [[0, 0, 0], [1, 1, 1], [0.2, 0.7, 0.4], [1, 0, 0], [0, 1, 0], [0, 0, 1]]
    ]
        ++ [ ( "image resize identity " ++ show method ++ " " ++ show (height, width)
             , ok
                ( do
                    a <- I.image [height, width] 1 [fromIntegral ((i * 13) `mod` 17) | i <- [0 .. height * width - 1]]
                    b <- I.resize method I.Reflect (height, width) a
                    Right (vec (I.imageValues a) (I.imageValues b))
                )
             )
           | method <- [I.Nearest, I.Bilinear, I.Bicubic, I.Lanczos]
           , height <- [1, 2, 4]
           , width <- [1, 3, 5]
           ]
        ++ [ ( "image gradient exact ramp " ++ show operator
             , ok
                ( do
                    a <-
                        I.image
                            [5, 5]
                            1
                            [2 * fromIntegral i + 3 * fromIntegral j | i <- [0 :: Int .. 4], j <- [0 :: Int .. 4]]
                    (r, c, m, _) <- I.gradient operator I.Clamp a
                    rp <- I.pixel r [2, 2]
                    cp <- I.pixel c [2, 2]
                    mp <- I.pixel m [2, 2]
                    Right (vec rp [2] && vec cp [3] && vec mp [sqrt 13])
                )
             )
           | operator <- [I.Sobel, I.Prewitt, I.Scharr]
           ]
        ++ [ ( "series change points exhaustive binary optimum " ++ show xs
             , ok
                ( do
                    breaks <- T.changePoints 0.3 1 xs
                    Right
                        (near (objective breaks xs) (minimum [objective cut xs | cut <- subsets [1 .. length xs - 1]]))
                )
             )
           | xs <- sequence (replicate 4 [0, 1])
           ]
        ++ [ ( "series DTW brute-force " ++ show (a, b)
             , ok (do r <- T.dynamicTimeWarping 4 a b; Right (near (T.dtwDistance r) (brute a b)))
             )
           | a <- sequence (replicate 2 [0, 1])
           , b <- sequence (replicate 3 [0, 1])
           ]
        ++ [ ( "image integral all rectangles " ++ show (height, width)
             , ok
                ( do
                    a <- I.image [height, width] 1 [fromIntegral (i `mod` 7) | i <- [0 .. height * width - 1]]
                    b <- I.integralImage a
                    answers <-
                        mapM
                            ( \(i, j, h, w) -> do
                                result <- I.rectangleSum (i, j) (h, w) b
                                Right
                                    (vec result [sum [I.imageValues a !! (r * width + c) | r <- [i .. i + h - 1], c <- [j .. j + w - 1]]])
                            )
                            [ (i, j, h, w) | i <- [0 .. height], j <- [0 .. width], h <- [0 .. height - i], w <- [0 .. width - j]
                            ]
                    Right (and answers)
                )
             )
           | height <- [1 .. 3]
           , width <- [1 .. 3]
           ]
  where
    subsets [] = [[]]
    subsets (x : xs) = let rest = subsets xs in rest ++ map (x :) rest
    objective breaks xs =
        0.3 * fromIntegral (length breaks)
            + sum
                [ let ys = take (b - a) (drop a xs); m = sum ys / fromIntegral (length ys)
                   in sum [(x - m) ^ (2 :: Int) | x <- ys]
                | (a, b) <- zip (0 : sort breaks) (sort breaks ++ [length xs])
                ]
    brute xs ys = go 0 0
      where
        go i j =
            abs (xs !! i - ys !! j)
                + if i == length xs - 1 && j == length ys - 1
                    then 0
                    else
                        minimum [go a b | (a, b) <- [(i + 1, j), (i, j + 1), (i + 1, j + 1)], a < length xs, b < length ys]
