{- | Analytic/independent reference checks for the complete time-series and
image scopes. Golden filters were generated by SciPy ndimage (reflect,
radius=1); ADF/KPSS/Yule--Walker by independent NumPy least-squares/Toeplitz
formulas. No Python dependency is needed to execute these stored checks.
-}
module ApplicationBatchSpec (applicationBatchTests) where

