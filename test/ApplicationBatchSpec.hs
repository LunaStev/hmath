                Right (all (\(x, y) -> abs (x - y) < 1e-3) (zip (I.imageValues b) [100, 0, 0]))
            )
        )
    ,
        ( "image grayscale linear luminance"
        , ok
            (do a <- I.image [1] 3 [1, 0, 0]; b <- I.grayscale I.SRGB a; Right (vec (I.imageValues b) [0.2126]))
        )
    ,
        ( "image histogram endpoints and equalization"
        , ok
            ( do
                a <- I.image [4] 1 [0, 0.25, 0.75, 1]
                h <- I.histogram 4 a
                b <- I.equalizeHistogram 4 a
                Right (h == [[1, 1, 0, 2]] && vec (I.imageValues b) [0, 1 / 3, 1, 1])
            )
        )
    ,
        ( "image histogram constant behavior"
        , ok
            ( do
                a <- I.image [3] 1 [0.2, 0.2, 0.2]
                b <- I.equalizeHistogram 8 a
                Right (a == b && isLeft (I.histogram 8 =<< I.brightness 2 a))
            )
        )
    ,
        ( "image CLAHE one tile CDF"
        , ok
            ( do
                a <- I.image [2, 2] 1 [0, 0.25, 0.5, 1]
                b <- I.clahe 4 (2, 2) 100 a
                Right (vec (I.imageValues b) [0.25, 0.5, 0.75, 1])
